const quaggaHeader = "! Generated by MoeDove IXP Manager; managed Quagga 1.2.4 route-server view.\n"
const quaggaModelPrefix = "! moedove-quagga-model "
const quaggaModelEnd = "! moedove-quagga-model-end"

type quaggaModel struct {
	Version int    `json:"version"`
	Router  Router `json:"router"`
	Peers   []Peer `json:"peers"`
}

// Quagga's RS-client Loc-RIB is independent of its main inbound filtering.
// Every destination gets an import map that matches the actual source peer and
// calls that source's complete prefix/path/next-hop policy. The same source
// policy also protects its main-RIB input and its RS export path.
func RenderQuagga(router Router, peers []Peer) (string, error) {
	role, _, err := normalizedRole(router)
	if err != nil {
		return "", err
	}
	if role != RoleRouteServer {
		return "", errors.New("Quagga 1.2.4 supports only the dedicated route-server view; collector and AS112 profiles are not verified")
	}
	if router.RPKI != nil {
		return "", errors.New("Quagga 1.2.4 has no verified runtime RPKI adapter")
	}
	if router.RFC1997Passthrough != nil {
		return "", errors.New("Quagga 1.2.4 has no verified RFC1997 policy override; explicit community policy cannot be substituted")
	}
	for _, peer := range peers {
		if len(peer.ID) > 256 {
			return "", errors.New("Quagga peer IDs exceed the bounded generated model")
		}
	}
	if _, err := Render(router, peers); err != nil {
		return "", err
	}
	router.Platform, router.Role = "quagga", RoleRouteServer
	router.ID, router.Name = "", "" // These labels have no routing semantics.
	for _, value := range []*string{&router.RouterID, &router.LocalIPv4, &router.LocalIPv6} {
		if *value != "" {
			ip, _ := netip.ParseAddr(*value)
			*value = ip.String()
		}
	}
	peers = enabledPeers(peers)
	names := map[string]bool{}
	for i := range peers {
		p := &peers[i]
		p.Name = ""
		name := peerName(*p)
		if names[name] {
			return "", errors.New("Quagga generated peer policy names collide")
		}
		names[name] = true
		ip, _ := netip.ParseAddr(p.Address)
		p.Address = ip.String()
		p.AllowedPrefixes = canonicalPrefixes(*p)
		pairs := []PrefixOrigin{}
		seen := map[string]bool{}
		for _, pair := range p.AllowedRoutes {
			prefix, _ := netip.ParsePrefix(pair.Prefix)
			pair.Prefix = prefix.String()
			key := fmt.Sprintf("%s/%d", pair.Prefix, pair.OriginASN)
			if !seen[key] {
				seen[key] = true
				pairs = append(pairs, pair)
			}
		}
		sort.Slice(pairs, func(i, j int) bool {
			if pairs[i].Prefix != pairs[j].Prefix {
				return pairs[i].Prefix < pairs[j].Prefix
			}
			return pairs[i].OriginASN < pairs[j].OriginASN
		})
		p.AllowedRoutes = pairs
	}
	raw, err := json.Marshal(quaggaModel{Version: 1, Router: router, Peers: peers})
	if err != nil {
		return "", err
	}
	encoded := base64.RawURLEncoding.EncodeToString(raw)
	var b strings.Builder
	b.WriteString(quaggaHeader)
	// Quagga's VTY config reader has bounded physical lines. The private-free
	// model is split into short comment lines rather than one enormous comment.
	for len(encoded) > 0 {
		n := 200
		if len(encoded) < n {
			n = len(encoded)
		}
		b.WriteString(quaggaModelPrefix + encoded[:n] + "\n")
		encoded = encoded[n:]
	}
	b.WriteString(quaggaModelEnd + "\n! Direct-peer NEXT_HOP only; no third-party next hops or local origination.\n! Stock Quagga RS community semantics; no community override is implied.\nhostname moedove-quagga-rs\nbgp multiple-instance\n!\n")
	for _, p := range peers {
		name := peerName(p)
		ip, _ := netip.ParseAddr(p.Address)
		family := "ip"
		if ip.Is6() {
			family = "ipv6"
		}
		if ip.Is4() {
			fmt.Fprintf(&b, "ip prefix-list %s_nh seq 5 permit %s/32\n", name, ip)
		}
		for _, group := range originGroups(p) {
			for i, prefix := range group.Prefixes {
				fmt.Fprintf(&b, "%s prefix-list %s seq %d permit %s\n", family, group.Name, (i+1)*5, prefix)
			}
			fmt.Fprintf(&b, "ip as-path access-list %s permit %s\n", group.Name, quaggaPathPattern(p.ASN, group.ASN))
		}
		sequence := 1
		for _, group := range originGroups(p) {
			fmt.Fprintf(&b, "route-map %s_policy permit %d\n match %s address prefix-list %s\n match as-path %s\n", name, sequence, family, group.Name, group.Name)
			if ip.Is4() {
				fmt.Fprintf(&b, " match ip next-hop prefix-list %s_nh\n", name)
			} else {
				fmt.Fprintf(&b, " match ipv6 next-hop %s\n", ip)
			}
			b.WriteString("!\n")
			sequence++
		}
		fmt.Fprintf(&b, "route-map %s_policy deny %d\n!\n", name, sequence)
	}
	for i, p := range peers {
		fmt.Fprintf(&b, "route-map mq_import permit %d\n match peer %s\n call %s_policy\n!\n", i+1, p.Address, peerName(p))
	}
	fmt.Fprintf(&b, "route-map mq_import deny %d\n!\nrouter bgp %d view MOEDOVE_QUAGGA\n bgp router-id %s\n bgp enforce-first-as\n no bgp default ipv4-unicast\n", len(peers)+1, router.ASN, router.RouterID)
	for _, p := range peers {
		ip, _ := netip.ParseAddr(p.Address)
		local := router.LocalIPv4
		if ip.Is6() {
			local = router.LocalIPv6
		}
		if comment := authenticationComment(p, false); comment != "" {
			fmt.Fprintf(&b, " ! %s\n", comment)
		}
		fmt.Fprintf(&b, " neighbor %s remote-as %d\n neighbor %s update-source %s\n", ip, p.ASN, ip, local)
		if p.Password != "" {
			fmt.Fprintf(&b, " neighbor %s password %s\n", ip, p.Password)
		}
	}
	for _, v4 := range []bool{true, false} {
		if v4 && router.LocalIPv4 == "" || !v4 && router.LocalIPv6 == "" {
			continue
		}
		family := "ipv6"
		if v4 {
			family = "ipv4"
		}
		fmt.Fprintf(&b, " address-family %s unicast\n", family)
		for _, p := range peers {
			ip, _ := netip.ParseAddr(p.Address)
			if ip.Is4() != v4 {
				continue
			}
			name := peerName(p)
			fmt.Fprintf(&b, "  neighbor %s activate\n  neighbor %s route-server-client\n  neighbor %s route-map %s_policy in\n  neighbor %s route-map %s_policy export\n  neighbor %s route-map mq_import import\n  neighbor %s maximum-prefix %d\n", ip, ip, ip, name, ip, name, ip, ip, p.MaxPrefixes)
			if !v4 {
				fmt.Fprintf(&b, "  neighbor %s nexthop-local unchanged\n", ip)
			}
		}
		b.WriteString(" exit-address-family\n")
	}
	b.WriteString("exit\n!\n")
	return boundedRendered(b.String(), nil)
}

// Stock bgp_regex.c compiles POSIX extended expressions and expands '_'.
// Anchoring both ends admits only nonempty, at most 64-AS canonical sequences;
// prefix and origin stay in the same route-map clause, never two unions.
func quaggaPathPattern(first, origin uint32) string {
	if origin == 0 {
		return fmt.Sprintf("^%d(_[0-9]+){0,63}$", first)
	}
	if first == origin {
		return fmt.Sprintf("^(%d|%d(_[0-9]+){0,62}_%d)$", first, first, origin)
	}
	return fmt.Sprintf("^%d(_[0-9]+){0,62}_%d$", first, origin)
}

var quaggaSecretLine = regexp.MustCompile(`^ neighbor ([0-9a-fA-F:.]+) password ([A-Za-z0-9+/=_-]{1,80})$`)

func parseManagedQuagga(config string) (quaggaModel, error) {
	fail := func() (quaggaModel, error) {
		return quaggaModel{}, errors.New("configuration is not an exact managed Quagga 1.2.4 route-server profile; raw content withheld")
	}
	if len(config) == 0 || len(config) > maxConfigSize || !strings.HasPrefix(config, quaggaHeader) || strings.ContainsAny(config, "\x00\r") || strings.Contains(config, RedactedBGPPassword) {
		return fail()
	}
	lines := strings.Split(config, "\n")
	var encoded strings.Builder
	at := 1
	for at < len(lines) && strings.HasPrefix(lines[at], quaggaModelPrefix) {
		part := strings.TrimPrefix(lines[at], quaggaModelPrefix)
		if len(part) == 0 || len(part) > 200 {
			return fail()
		}
		encoded.WriteString(part)
		at++
	}
	if at >= len(lines) || lines[at] != quaggaModelEnd {
		return fail()
	}
	raw, err := base64.RawURLEncoding.DecodeString(encoded.String())
	if err != nil {
		return fail()
	}
	decoder := json.NewDecoder(strings.NewReader(string(raw)))
	decoder.DisallowUnknownFields()
	var model quaggaModel
	if decoder.Decode(&model) != nil || decoder.Decode(new(any)) != io.EOF || model.Version != 1 {
		return fail()
	}
	byAddress := map[string]int{}
	for i, p := range model.Peers {
		if _, found := byAddress[p.Address]; found {
			return fail()
		}
		byAddress[p.Address] = i
	}
	seen := map[string]bool{}
	for _, line := range lines[at+1:] {
		if strings.Contains(line, " password ") {
			match := quaggaSecretLine.FindStringSubmatch(line)
			if match == nil {
				return fail()
			}
			i, ok := byAddress[match[1]]
			if !ok || seen[match[1]] {
				return fail()
			}
			seen[match[1]] = true
			model.Peers[i].Password = match[2]
		}
	}
	want, err := RenderQuagga(model.Router, model.Peers)
	if err != nil || want != config {
		return fail()
	}
	return model, nil
}
func ValidateManagedQuagga(config string) error { _, err := parseManagedQuagga(config); return err }
func RedactQuagga(config string) (string, error) {
	if _, err := parseManagedQuagga(config); err != nil {
		return "", err
	}
	lines := strings.Split(config, "\n")
	for i, line := range lines {
		if match := quaggaSecretLine.FindStringSubmatch(line); match != nil {
			lines[i] = " neighbor " + match[1] + " password " + RedactedBGPPassword
		}
	}
	return strings.Join(lines, "\n"), nil
}
