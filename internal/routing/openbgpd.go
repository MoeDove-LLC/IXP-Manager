const openBGPDHeader = "# Generated by MoeDove IXP Manager; managed OpenBGPD 8.8+ profile.\n"

// A dedicated instance has one pinned private administrative endpoint. The
// watchdog verifies its Linux peer credentials against the configured parent PID.
const OpenBGPDControlSocket = "/run/moedove-openbgpd/bgpd.sock"
const openBGPDModelPrefix = "# moedove-model "

type openBGPDModel struct {
	Version int    `json:"version"`
	Router  Router `json:"router"`
	Peers   []Peer `json:"peers"`
}

// RenderOpenBGPD generates an entire dedicated-instance configuration. The
// encoded model contains no passwords and permits exact grammar reconstruction
// before a native checker or privileged reload can see an artifact.
func RenderOpenBGPD(router Router, peers []Peer) (string, error) {
	if router.Role == RoleAS112 {
		return renderAS112("openbgpd", router, peers)
	}
	role, policy, err := normalizedRole(router)
	if err != nil {
		return "", err
	}
	if router.RPKI != nil {
		return "", errors.New("OpenBGPD has no verified runtime RPKI adapter in this application")
	}
	if _, err = Render(router, peers); err != nil {
		return "", err
	}
	router.Role, router.CollectorPolicy, router.Platform = role, policy, "openbgpd"
	for _, value := range []*string{&router.RouterID, &router.LocalIPv4, &router.LocalIPv6} {
		if *value != "" {
			a, _ := netip.ParseAddr(*value)
			*value = a.String()
		}
	}
	peers = enabledPeers(peers)
	for i := range peers {
		p := &peers[i]
		ip, _ := netip.ParseAddr(p.Address)
		p.Address = ip.String()
		p.AllowedPrefixes = canonicalPrefixes(*p)
		pairs := []PrefixOrigin{}
		seen := map[string]bool{}
		for _, r := range p.AllowedRoutes {
			prefix, _ := netip.ParsePrefix(r.Prefix)
			r.Prefix = prefix.String()
			key := fmt.Sprintf("%s/%d", r.Prefix, r.OriginASN)
			if !seen[key] {
				seen[key] = true
				pairs = append(pairs, r)
			}
		}
		sort.Slice(pairs, func(i, j int) bool {
			if pairs[i].Prefix != pairs[j].Prefix {
				return pairs[i].Prefix < pairs[j].Prefix
			}
			return pairs[i].OriginASN < pairs[j].OriginASN
		})
		p.AllowedRoutes = pairs
	}
	model, err := json.Marshal(openBGPDModel{1, router, peers})
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(openBGPDHeader)
	b.WriteString(openBGPDModelPrefix + base64.RawURLEncoding.EncodeToString(model) + "\n")
	fmt.Fprintf(&b, "AS %d\nrouter-id %s\nfib-update no\nreject as-set yes\n", router.ASN, router.RouterID)
	fmt.Fprintf(&b, "socket \"%s\"\n", OpenBGPDControlSocket)
	collector := role == RoleRouteCollector
	if collector {
		b.WriteString("rde rib MOEDOVE no evaluate\n")
		if policy == CollectorObserve {
			b.WriteString("rde rib Loc-RIB include filtered\n")
		}
	} else {
		b.WriteString("rde rib MOEDOVE\nrde evaluate all\ntransparent-as yes\n")
	}
	for _, local := range []string{router.LocalIPv4, router.LocalIPv6} {
		if local != "" {
			fmt.Fprintf(&b, "listen on %s\n", local)
		}
	}
	for _, p := range peers {
		for _, group := range originGroups(p) {
			if len(group.Prefixes) == 0 {
				continue
			}
			setType := "prefix-set"
			if group.ASN != 0 {
				setType = "origin-set"
			}
			fmt.Fprintf(&b, "%s %s {\n", setType, group.Name)
			for _, prefix := range group.Prefixes {
				fmt.Fprintf(&b, "  %s", prefix)
				if group.ASN != 0 {
					fmt.Fprintf(&b, " source-as %d", group.ASN)
				}
				b.WriteString("\n")
			}
			b.WriteString("}\n")
		}
	}
	for _, p := range peers {
		ip, _ := netip.ParseAddr(p.Address)
		local := router.LocalIPv4
		family := "inet"
		if ip.Is6() {
			local = router.LocalIPv6
			family = "inet6"
		}
		fmt.Fprintf(&b, "neighbor %s {\n  descr \"%s\"\n  remote-as %d\n  local-address %s\n  announce %s unicast\n  announce %s none\n  rib MOEDOVE\n  enforce neighbor-as yes\n  enforce local-as yes\n  max-prefix %d\n", ip, peerName(p), p.ASN, local, family, map[string]string{"inet": "inet6", "inet6": "inet"}[family], p.MaxPrefixes)
		if collector {
			b.WriteString("  export none\n")
		} else {
			b.WriteString("  set nexthop no-modify\n")
		}
		if comment := authenticationComment(p, false); comment != "" {
			b.WriteString("  # " + comment + "\n")
		}
		if p.Password != "" {
			fmt.Fprintf(&b, "  tcp md5sig password \"%s\"\n", p.Password)
		}
		b.WriteString("}\n")
	}
	b.WriteString("deny from any\ndeny to any\ndeny quick from any max-as-len 64\n")
	for _, p := range peers {
		for _, group := range originGroups(p) {
			if len(group.Prefixes) == 0 {
				continue
			}
			setType := "prefix-set"
			if group.ASN != 0 {
				setType = "origin-set"
			}
			fmt.Fprintf(&b, "allow from %s peer-as %d %s %s", p.Address, p.ASN, setType, group.Name)
			b.WriteString("\n")
		}
	}
	if !collector {
		// RFC 7947 attribute transparency includes communities. Do not add
		// implicit NO_EXPORT/NO_ADVERTISE policy that the user did not select.
		b.WriteString("allow to any\n")
		if router.RFC1997Passthrough != nil && !*router.RFC1997Passthrough {
			b.WriteString("deny quick to any community NO_EXPORT\ndeny quick to any community NO_ADVERTISE\ndeny quick to any community NO_EXPORT_SUBCONFED\n")
		}
	}
	return boundedRendered(b.String(), nil)
}

var openBGPDNeighbor = regexp.MustCompile(`^neighbor ([0-9a-f:.]+) \{$`)
var openBGPDPassword = regexp.MustCompile(`^  tcp md5sig password "([A-Za-z0-9+/=_-]{1,80})"$`)

func parseManagedOpenBGPD(config string) (openBGPDModel, error) {
	if isAS112Artifact("openbgpd", config) {
		m, err := parseAS112Artifact("openbgpd", config)
		return openBGPDModel{Version: 1, Router: m.Router, Peers: m.Peers}, err
	}
	var model openBGPDModel
	fail := func() (openBGPDModel, error) {
		return openBGPDModel{}, errors.New("configuration is not an exact managed OpenBGPD profile; raw content withheld")
	}
	if len(config) == 0 || len(config) > maxConfigSize || !strings.HasPrefix(config, openBGPDHeader+openBGPDModelPrefix) || strings.Contains(config, RedactedBGPPassword) {
		return fail()
	}
	lines := strings.Split(config, "\n")
	raw, err := base64.RawURLEncoding.DecodeString(strings.TrimPrefix(lines[1], openBGPDModelPrefix))
	if err != nil {
		return fail()
	}
	d := json.NewDecoder(strings.NewReader(string(raw)))
	d.DisallowUnknownFields()
	if d.Decode(&model) != nil || d.Decode(new(any)) != io.EOF || model.Version != 1 {
		return fail()
	}
	byAddress := map[string]int{}
	for i, p := range model.Peers {
		if _, ok := byAddress[p.Address]; ok {
			return fail()
		}
		byAddress[p.Address] = i
	}
	current := ""
	secrets := map[string]bool{}
	for _, line := range lines[2:] {
		if match := openBGPDNeighbor.FindStringSubmatch(line); match != nil {
			current = match[1]
		}
		if line == "}" {
			current = ""
		}
		if strings.Contains(line, "tcp md5sig") {
			match := openBGPDPassword.FindStringSubmatch(line)
			index, exists := byAddress[current]
			if match == nil || !exists || secrets[current] {
				return fail()
			}
			secrets[current] = true
			model.Peers[index].Password = match[1]
		}
	}
	want, err := RenderOpenBGPD(model.Router, model.Peers)
	if err != nil || want != config {
		return fail()
	}
	return model, nil
}
func ValidateManagedOpenBGPD(config string) error { _, err := parseManagedOpenBGPD(config); return err }
func RedactOpenBGPD(config string) (string, error) {
	if _, err := parseManagedOpenBGPD(config); err != nil {
		return "", err
	}
	lines := strings.Split(config, "\n")
	for i, line := range lines {
		if openBGPDPassword.MatchString(line) {
			lines[i] = "  tcp md5sig password \"" + RedactedBGPPassword + "\""
		}
	}
	return strings.Join(lines, "\n"), nil
}
func ValidateOpenBGPD(ctx context.Context, binary, config string) error {
	if err := ValidateManagedOpenBGPD(config); err != nil {
		return err
	}
	if binary == "" {
		binary = "bgpd"
	}
	ctx, cancel := context.WithTimeout(ctx, 15*time.Second)
	defer cancel()
	version, err := run(ctx, binary, "-V")
	if err != nil {
		return nativeFailure("OpenBGPD executable unavailable", err)
	}
	if !regexp.MustCompile(`(?m)^OpenBGPD (8\.(?:[8-9]|[1-9][0-9]+)|(?:[9]|[1-9][0-9]+)\.[0-9]+)(?:\s|$)`).MatchString(version) {
		return errors.New("native validation requires OpenBGPD portable 8.8 or newer")
	}
	f, err := os.CreateTemp("", "moedove-openbgpd-*.conf")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err = f.WriteString(config); err != nil {
		f.Close()
		return err
	}
	if err = f.Close(); err != nil {
		return err
	}
	out, err := run(ctx, binary, "-n", "-f", f.Name())
	if err != nil {
		return nativeFailure("OpenBGPD native syntax validation rejected configuration", err)
	}
	if strings.TrimSpace(out) != "configuration OK" {
		return errors.New("OpenBGPD did not report successful configuration validation; diagnostics withheld")
	}
	return nil
}
