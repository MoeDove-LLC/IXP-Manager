var errUnsafeRedaction = errors.New("configuration is not a recognized generated format; no preview returned")
var authCommentPattern = regexp.MustCompile(`^moedove-auth peer=md_[0-9a-f]{16} revision=[A-Za-z0-9_-]{22} state=(tcp-md5|disabled)$`)
var xmlAuthCommentPattern = regexp.MustCompile(`^moedove-auth peer=md_[0-9a-f]{16} revision-hex=[a-f0-9]{44} state=(tcp-md5|disabled)$`)
var birdPasswordLine = regexp.MustCompile(`^(\s*password ")[A-Za-z0-9+/=_-]{1,80}(";\s*)$`)
var frrPasswordLine = regexp.MustCompile(`^(\s*neighbor [0-9a-fA-F:.]+ password )[A-Za-z0-9+/=_-]{1,80}(\s*)$`)
