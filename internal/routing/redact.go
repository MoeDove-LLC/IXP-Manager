func redactRouterOS(config string) (string, error) {
	header := "# MoeDove IXP Manager - RouterOS 7.20+ bootstrap preview\n# All connections remain disabled. Validate on the target before activation.\n# Re-import is refused; no existing device objects are removed.\n"
	if !strings.HasPrefix(config, header) {
		return "", errUnsafeRedaction
	}
	lines := strings.Split(strings.TrimPrefix(config, header), "\n")
	for i, line := range lines {
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "# ") && authCommentPattern.MatchString(strings.TrimPrefix(line, "# ")) {
			continue
		}
		if routerOSConnection.MatchString(line) {
			lines[i] = routerOSPasswordSuffix.ReplaceAllString(line, ` tcp-md5-key="`+RedactedBGPPassword+`"`)
			continue
		}
		allowed := false
		for _, pattern := range routerOSSafeLines {
			if pattern.MatchString(line) {
				allowed = true
				break
			}
		}
		if !allowed {
			return "", errUnsafeRedaction
		}
	}
	return header + strings.Join(lines, "\n"), nil
}

