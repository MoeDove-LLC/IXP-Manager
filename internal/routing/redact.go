// RedactConfig is a generated-artifact parser, not a best-effort regex filter for
// arbitrary vendor configuration. Unexpected input returns NO content. The
// returned placeholder is deliberately rejected by native validation routines.
func RedactConfig(platform, config string) (string, error) {
	if len(config) == 0 || len(config) > maxConfigSize || strings.ContainsAny(config, "\x00\r") {
		return "", errUnsafeRedaction
	}
	// Every renderer emits ASCII only (free text is never interpolated). Reject
	// Unicode whitespace rather than let TrimSpace accept a password line that
	// the ASCII command recognizer cannot safely rewrite.
	for i := 0; i < len(config); i++ {
		if config[i] > 126 || (config[i] < 32 && config[i] != '\n' && config[i] != '\t') {
			return "", errUnsafeRedaction
		}
	}
	if platform == "" {
		platform = "bird2"
	}
	if isAS112Artifact(platform, config) {
		return redactAS112(platform, config)
	}
	switch platform {
	case "", "bird2":
		return redactBIRD(config)
	case "bird3":
		return RedactBIRD3(config)
	case "quagga":
		return RedactQuagga(config)
	case "bird1":
		return RedactBIRD1(config)
	case "openbgpd":
		return RedactOpenBGPD(config)
	case "frr":
		if err := ValidateManagedFRR(config); err != nil {
			return "", errUnsafeRedaction
		}
		lines := strings.Split(config, "\n")
		for i, line := range lines {
			if frrPasswordLine.MatchString(line) {
				lines[i] = frrPasswordLine.ReplaceAllString(line, "${1}"+RedactedBGPPassword+"${2}")
			}
		}
		return strings.Join(lines, "\n"), nil
	case "junos":
		return redactJunos(config)
	case "routeros7":
		return redactRouterOS(config)
	default:
		return "", errUnsafeRedaction
	}
}

