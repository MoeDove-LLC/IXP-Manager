func redactBIRD(config string) (string, error) {
	if !strings.HasPrefix(config, "# Generated by MoeDove IXP Manager. BIRD 2; exact prefix allowlists.\n") && !strings.HasPrefix(config, "# Generated by MoeDove IXP Manager. BIRD 2; route collector.\n") {
		return "", errUnsafeRedaction
	}
	lines := strings.Split(config, "\n")
	for i, line := range lines {
		if i == 0 {
			continue
		}
		trim := strings.TrimSpace(line)
		if trim == "" {
			continue
		}
		if strings.HasPrefix(trim, "# ") && authCommentPattern.MatchString(strings.TrimPrefix(trim, "# ")) {
			continue
		}
		if birdPasswordLine.MatchString(line) {
			lines[i] = birdPasswordLine.ReplaceAllString(line, "${1}"+RedactedBGPPassword+"${2}")
			continue
		}
		allowed := false
		for _, pattern := range birdSafeLines {
			if pattern.MatchString(trim) {
				allowed = true
				break
			}
		}
		if !allowed {
			return "", errUnsafeRedaction
		}
	}
	return strings.Join(lines, "\n"), nil
}

