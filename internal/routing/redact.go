var junosSymbol = regexp.MustCompile(`^(moedove_[a-f0-9]{16}(_export)?|md_[a-f0-9]{16}(_o[0-9]+)?(_import|_first_as|_origin)?|default_deny)$`)
var junosPathValue = regexp.MustCompile(`^([0-9]+ \.\{0,63\}|[0-9]+ \.\{0,62\} [0-9]+|\([0-9]+\|[0-9]+ \.\{0,62\} [0-9]+\))$`)
var digitsOnly = regexp.MustCompile(`^[0-9]+$`)

func safeJunosText(path, value string) bool {
	leaf := path[strings.LastIndex(path, "/")+1:]
	switch leaf {
	case "name":
		if strings.HasSuffix(path, "/neighbor/name") {
			_, err := netip.ParseAddr(value)
			return err == nil
		}
		return junosSymbol.MatchString(value)
	case "protocol":
		return value == "bgp"
	case "type":
		return value == "external"
	case "as-path", "import", "export", "apply-groups":
		return junosSymbol.MatchString(value)
	case "path":
		return junosPathValue.MatchString(value)
	case "address":
		p, err := netip.ParsePrefix(value)
		return err == nil && p == p.Masked()
	case "local-address", "router-id":
		_, err := netip.ParseAddr(value)
		return err == nil
	case "maximum", "peer-as", "as-number":
		return digitsOnly.MatchString(value)
	}
	return false
}
func redactJunos(config string) (string, error) {
	if err := ValidateJunosXML(config); err != nil {
		return "", errUnsafeRedaction
	}
	decoder := xml.NewDecoder(strings.NewReader(config))
	var output bytes.Buffer
	encoder := xml.NewEncoder(&output)
	stack := []string{}
	inKey := false
	var key strings.Builder
	for {
		token, err := decoder.Token()
		if err == io.EOF {
			break
		}
		if err != nil {
			return "", errUnsafeRedaction
		}
		switch value := token.(type) {
		case xml.StartElement:
			if inKey || value.Name.Space != "" {
				return "", errUnsafeRedaction
			}
			stack = append(stack, value.Name.Local)
			path := strings.Join(stack, "/")
			if !junosPaths[path] {
				return "", errUnsafeRedaction
			}
			attributes := make([]xml.Attr, 0, len(value.Attr))
			for _, attr := range value.Attr {
				if attr.Name.Local == "operation" && attr.Name.Space == netconfNS && attr.Value == "replace" && path == "configuration/groups" {
					attributes = append(attributes, attr)
					continue
				}
				if (attr.Name.Space == "xmlns" || attr.Name.Local == "xmlns") && (attr.Value == "" || attr.Value == netconfNS) {
					// The decoder exposes prefix declarations as attributes in
					// the special "xmlns" space. EncodeToken already declares
					// the namespace for operation; replaying these would invent
					// an _xmlns namespace and misrepresent the reviewed XML.
					if attr.Name.Space != "xmlns" {
						attributes = append(attributes, attr)
					}
					continue
				}
				return "", errUnsafeRedaction
			}
			value.Attr = attributes
			token = value
			if value.Name.Local == "authentication-key" {
				inKey = true
				key.Reset()
			}
		case xml.EndElement:
			if inKey {
				if value.Name.Local != "authentication-key" || ValidateBGPPassword(key.String()) != nil {
					return "", errUnsafeRedaction
				}
				if err = encoder.EncodeToken(xml.CharData(RedactedBGPPassword)); err != nil {
					return "", errUnsafeRedaction
				}
				inKey = false
			}
			stack = stack[:len(stack)-1]
		case xml.CharData:
			if inKey {
				key.Write(value)
				continue
			}
			text := strings.TrimSpace(string(value))
			if text != "" && !safeJunosText(strings.Join(stack, "/"), text) {
				return "", errUnsafeRedaction
			}
		case xml.Comment:
			if inKey || !xmlAuthCommentPattern.MatchString(strings.TrimSpace(string(value))) {
				return "", errUnsafeRedaction
			}
		default:
			return "", errUnsafeRedaction
		}
		if err = encoder.EncodeToken(token); err != nil {
			return "", errUnsafeRedaction
		}
	}
	if err := encoder.Flush(); err != nil {
		return "", errUnsafeRedaction
	}
	return output.String(), nil
}
