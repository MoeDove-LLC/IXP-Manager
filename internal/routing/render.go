// Package routing renders a deliberately constrained BIRD 2 route-server policy.
package routing

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"net/netip"
	"sort"
	"strings"
)

type Router struct {
	AS112Service       string      `json:"as112Service,omitempty"`
	AS112IPv4          bool        `json:"as112IPv4,omitempty"`
	AS112IPv6          bool        `json:"as112IPv6,omitempty"`
	AS112NextHop4      string      `json:"as112NextHop4,omitempty"`
	AS112NextHop6      string      `json:"as112NextHop6,omitempty"`
	RFC1997Passthrough *bool       `json:"rfc1997Passthrough,omitempty"`
	Role               string      `json:"role,omitempty"`
	CollectorPolicy    string      `json:"collectorPolicy,omitempty"`
	RPKI               *RPKIConfig `json:"rpki,omitempty"`
	Platform           string      `json:"platform"`
	ID                 string      `json:"id"`
	Name               string      `json:"name"`
	ASN                uint32      `json:"asn"`
	RouterID           string      `json:"routerId"`
	LocalIPv4          string      `json:"localIpv4"`
	LocalIPv6          string      `json:"localIpv6"`
}

type Peer struct {
	Password               string         `json:"-"`
	AuthenticationRevision string         `json:"authenticationRevision,omitempty"`
	AllowedRoutes          []PrefixOrigin `json:"allowedRoutes,omitempty"`
	ID                     string         `json:"id"`
	Name                   string         `json:"name"`
	ASN                    uint32         `json:"asn"`
	Address                string         `json:"address"`
	Enabled                bool           `json:"enabled"`
	MaxPrefixes            int            `json:"maxPrefixes"`
	AllowedPrefixes        []string       `json:"allowedPrefixes"`
}

func Checksum(config string) string {
	sum := sha256.Sum256([]byte(config))
	return hex.EncodeToString(sum[:])
}

func validASN(asn uint32) bool { return asn != 0 && asn != 23456 && asn != 65535 && asn != 4294967295 }
func address(raw string) (netip.Addr, error) {
	a, e := netip.ParseAddr(raw)
	if e != nil || a.Zone() != "" || a.Is4In6() || !a.IsGlobalUnicast() {
		return netip.Addr{}, errors.New("must be a unicast IP address without a zone")
	}
	return a, nil
}

// Render never interpolates names, arbitrary policy expressions, file paths, or
// shell commands. Only parsed IPs, canonical prefixes and integers reach BIRD.
// Prefixes are exact matches: adding a /24 does not implicitly allow its /32s.
func Render(router Router, peers []Peer) (string, error) {
	if router.Role == RoleAS112 {
		return renderAS112("bird2", router, peers)
	}
	role, collectorPolicy, err := normalizedRole(router)
	if err != nil {
		return "", err
	}
	collector := role == RoleRouteCollector
	for _, peer := range peers {
		if err := validatePeerAuthentication(peer); err != nil {
			return "", err
		}
	}
	rpki, rpkiErr := normalizeRPKI(router.RPKI)
	if rpkiErr != nil {
		return "", rpkiErr
	}
	if !validASN(router.ASN) {
		return "", errors.New("router ASN is invalid")
	}
	rid, err := address(router.RouterID)
	if err != nil || !rid.Is4() {
		return "", errors.New("routerId must be a unicast IPv4 address")
	}
	locals := map[bool]netip.Addr{}
	for _, pair := range []struct {
		v    string
		ipv4 bool
	}{{router.LocalIPv4, true}, {router.LocalIPv6, false}} {
		if pair.v == "" {
			continue
		}
		a, e := address(pair.v)
		if e != nil || a.Is4() != pair.ipv4 {
			return "", errors.New("local address family is invalid")
		}
		locals[pair.ipv4] = a
	}
	if len(locals) == 0 {
		return "", errors.New("at least one local router address is required")
	}
	if len(peers) > 10000 {
		return "", errors.New("too many peers")
	}
	// Cap total work before constructing any vendor output. Per-peer limits
	// alone would otherwise permit gigabytes across a large router inventory.
	total := 0
	for _, peer := range peers {
		if !peer.Enabled {
			continue
		}
		total += len(peer.AllowedPrefixes) + len(peer.AllowedRoutes)
		if total > 20000 {
			return "", errors.New("router policy exceeds 20000 combined prefix/origin entries; split the reviewed policy across router instances")
		}
	}
	ordered := append([]Peer(nil), peers...)
	sort.Slice(ordered, func(i, j int) bool { return ordered[i].ID < ordered[j].ID })
	var b strings.Builder
	if collector {
		fmt.Fprintf(&b, "# Generated by MoeDove IXP Manager. BIRD 2; route collector.\n# moedove-role role=route-collector policy=%s\nrouter id %s;\nlog stderr { warning, error, fatal };\nprotocol device { scan time 60; }\n\n", collectorPolicy, rid)
	} else {
		fmt.Fprintf(&b, "# Generated by MoeDove IXP Manager. BIRD 2; exact prefix allowlists.\nrouter id %s;\nlog stderr { warning, error, fatal };\nprotocol device { scan time 60; }\n\n", rid)
	}
	if rpki != nil {
		b.WriteString(birdRPKI(rpki))
	}
	seenIDs := map[string]bool{}
	seenIPs := map[netip.Addr]bool{}
	for _, p := range ordered {
		if !p.Enabled {
			continue
		}
		if p.ID == "" || seenIDs[p.ID] {
			return "", errors.New("enabled peers require unique IDs")
		}
		seenIDs[p.ID] = true
		if !validASN(p.ASN) || p.ASN == router.ASN {
			return "", fmt.Errorf("peer %s has invalid external ASN", p.ID)
		}
		ip, e := address(p.Address)
		if e != nil {
			return "", fmt.Errorf("peer %s: invalid address", p.ID)
		}
		local, ok := locals[ip.Is4()]
		if !ok {
			return "", fmt.Errorf("peer %s: router has no local address for its family", p.ID)
		}
		if ip == local || seenIPs[ip] {
			return "", fmt.Errorf("peer %s: duplicate or local address", p.ID)
		}
		seenIPs[ip] = true
		if p.MaxPrefixes < 1 || p.MaxPrefixes > 1000000 {
			return "", fmt.Errorf("peer %s: maxPrefixes must be 1..1000000", p.ID)
		}
		if (len(p.AllowedPrefixes) == 0 && !(collector && collectorPolicy == CollectorObserve)) || len(p.AllowedPrefixes) > 10000 {
			return "", fmt.Errorf("peer %s: explicit prefix allowlist required (maximum 10000)", p.ID)
		}
		prefixes := make([]string, 0, len(p.AllowedPrefixes))
		seenPrefixes := map[string]bool{}
		for _, raw := range p.AllowedPrefixes {
			prefix, e := netip.ParsePrefix(raw)
			if e != nil || prefix.Addr().Is4() != ip.Is4() || prefix.Addr().Is4In6() || prefix.Bits() == 0 || prefix != prefix.Masked() || !prefix.Addr().IsGlobalUnicast() {
				return "", fmt.Errorf("peer %s: invalid canonical prefix or address family", p.ID)
			}
			s := prefix.String()
			if !seenPrefixes[s] {
				prefixes = append(prefixes, s)
				seenPrefixes[s] = true
			}
		}
		if err := validatePrefixOrigins(p, ip.Is4()); err != nil {
			return "", err
		}
		sort.Strings(prefixes)
		family := "ipv6"
		if ip.Is4() {
			family = "ipv4"
		}
		rpkiChannel := ""
		rpkiFilter := birdOriginGuard(p)
		if rpki != nil {
			table := "md_roa6"
			if ip.Is4() {
				table = "md_roa4"
			}
			rpkiChannel = "    import table yes;\n    rpki reload on;\n"
			if !collector {
				rpkiChannel += "    import keep filtered yes;\n"
			}
			rpkiFilter += fmt.Sprintf("      if roa_check(%s, net, bgp_path.last) != ROA_VALID then reject;\n", table)
		}
		authentication := ""
		if !collector && router.RFC1997Passthrough != nil && *router.RFC1997Passthrough {
			authentication = "  interpret communities off;\n"
		}
		if comment := authenticationComment(p, false); comment != "" {
			fmt.Fprintf(&b, "# %s\n", comment)
		}
		if p.Password != "" {
			authentication += fmt.Sprintf("  authentication md5;\n  password \"%s\";\n", p.Password)
		}
		protocol := "peer_" + Checksum(p.ID)[:20]
		if collector {
			writeBIRDCollectorPeer(&b, collectorPolicy, p, protocol, local.String(), router.ASN, ip.String(), authentication, family, rpkiChannel, rpkiFilter, prefixes)
			continue
		}
		receiveLimit := ""
		if rpki != nil {
			receiveLimit = fmt.Sprintf("    receive limit %d action disable;\n", p.MaxPrefixes)
		}
		fmt.Fprintf(&b, "protocol bgp %s {\n  local %s as %d;\n  neighbor %s as %d;\n  rs client;\n  enforce first as on;\n%s  %s {\n%s    import filter {\n      if bgp_path.len = 0 then reject;\n      if bgp_path.len > 64 then reject;\n      if bgp_path.first != %d then reject;\n      if net !~ [ %s ] then reject;\n%s      accept;\n    };\n    import limit %d action block;\n%s    export filter {\n      if source != RTS_BGP then reject;\n      accept;\n    };\n  };\n}\n\n", protocol, local, router.ASN, ip, p.ASN, authentication, family, rpkiChannel, p.ASN, strings.Join(prefixes, ", "), rpkiFilter, p.MaxPrefixes, receiveLimit)
	}
	return b.String(), nil
}
