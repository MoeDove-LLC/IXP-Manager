const RoleAS112 = "as112"

type as112RoutingModel struct {
	Version  int    `json:"version"`
	Platform string `json:"platform"`
	Router   Router `json:"router"`
	Peers    []Peer `json:"peers"`
}

func AS112Service(router Router) as112.Service {
	return as112.Service{Mode: router.AS112Service, IPv4: router.AS112IPv4, IPv6: router.AS112IPv6}
}
func validateAS112(router Router, peers []Peer) error {
	if router.Role != RoleAS112 || router.ASN != as112.ASN {
		return errors.New("AS112 requires role as112 and fixed ASN 112")
	}
	if err := AS112Service(router).Validate(); err != nil {
		return err
	}
	if router.Platform == "junos" {
		for _, next := range []struct {
			value       string
			v4, enabled bool
		}{{router.AS112NextHop4, true, router.AS112IPv4}, {router.AS112NextHop6, false, router.AS112IPv6}} {
			if !next.enabled {
				if next.value != "" {
					return errors.New("Junos DNS next hop requires its AS112 family")
				}
				continue
			}
			ip, err := address(next.value)
			if err != nil || ip.Is4() != next.v4 {
				return errors.New("Junos AS112 requires a DNS next hop for each enabled family")
			}
			for _, local := range []string{router.LocalIPv4, router.LocalIPv6} {
				if value, e := netip.ParseAddr(local); e == nil && ip == value {
					return errors.New("Junos AS112 DNS next hop cannot be the router itself")
				}
			}
			for _, raw := range (as112.Service{Mode: as112.Both, IPv4: true, IPv6: true}).Prefixes() {
				prefix, _ := netip.ParsePrefix(raw)
				if prefix.Contains(ip) {
					return errors.New("Junos AS112 DNS next hop cannot use an anycast service prefix")
				}
			}
		}
	} else if router.AS112NextHop4 != "" || router.AS112NextHop6 != "" {
		return errors.New("AS112 DNS next-hop fields are only supported by the Junos forwarding profile")
	}
	if router.CollectorPolicy != "" || router.RPKI != nil || router.RFC1997Passthrough != nil {
		return errors.New("AS112 has fixed origin-only policy; collector/RPKI/RFC1997 controls are not applicable")
	}
	rid, err := address(router.RouterID)
	if err != nil || !rid.Is4() {
		return errors.New("AS112 router ID must be unicast IPv4")
	}
	for _, value := range []struct {
		ip      string
		v4      bool
		enabled bool
	}{{router.LocalIPv4, true, router.AS112IPv4}, {router.LocalIPv6, false, router.AS112IPv6}} {
		if value.ip == "" {
			if value.enabled {
				return errors.New("each enabled AS112 family requires its local BGP transport address")
			}
			continue
		}
		ip, e := address(value.ip)
		if e != nil || ip.Is4() != value.v4 {
			return errors.New("AS112 local address family invalid")
		}
	}
	if len(peers) > 10000 {
		return errors.New("too many AS112 peers")
	}
	ids, ips := map[string]bool{}, map[netip.Addr]bool{}
	for _, p := range peers {
		if err := validatePeerAuthentication(p); err != nil {
			return err
		}
		if !p.Enabled {
			continue
		}
		ip, err := address(p.Address)
		if err != nil || p.ID == "" || ids[p.ID] || ips[ip] || !validASN(p.ASN) || p.ASN == as112.ASN || p.MaxPrefixes < 1 || p.MaxPrefixes > 1000000 {
			return errors.New("AS112 peer identity, address, ASN or receive bound is invalid")
		}
		local := router.LocalIPv4
		family := router.AS112IPv4
		if ip.Is6() {
			local = router.LocalIPv6
			family = router.AS112IPv6
		}
		source, e := address(local)
		if !family || e != nil || source.Is4() != ip.Is4() || source == ip {
			return errors.New("AS112 peer requires its explicitly enabled family and local transport address")
		}
		if len(p.AllowedPrefixes) > 0 || len(p.AllowedRoutes) > 0 {
			return errors.New("AS112 peers reject all received routes; remove obsolete ingress allowlists explicitly")
		}
		ids[p.ID], ips[ip] = true, true
	}
	return nil
}
func as112Header(platform string) string {
	switch platform {
	case "bird2":
		return "# Generated by MoeDove IXP Manager. BIRD 2; AS112 origin-only.\n"
	case "bird3":
		return "# Generated by MoeDove IXP Manager. BIRD 3; AS112 origin-only.\n"
	case "frr":
		return "! Generated by MoeDove IXP Manager; AS112 origin-only view.\n"
	case "openbgpd":
		return "# Generated by MoeDove IXP Manager; AS112 OpenBGPD origin-only.\n"
	case "junos":
		return "<!-- Generated by MoeDove IXP Manager; AS112 origin-only. -->\n"
	}
	return ""
}
func as112ModelLine(platform, encoded string) string {
	if platform == "junos" {
		return "<!-- moedove-as112 " + encoded + " -->\n"
	}
	prefix := "#"
	if platform == "frr" {
		prefix = "!"
	}
	return prefix + " moedove-as112 " + encoded + "\n"
}
func isAS112Artifact(platform, config string) bool {
	header := as112Header(platform)
	return header != "" && strings.HasPrefix(config, header)
}
func renderAS112(platform string, router Router, peers []Peer) (string, error) {
	return renderAS112Version(platform, router, peers, false)
}
func renderAS112Version(platform string, router Router, peers []Peer, historical bool) (string, error) {
	if as112Header(platform) == "" {
		return "", errors.New("platform has no AS112 adapter")
	}
	router.Platform = platform
	if err := validateAS112(router, peers); err != nil {
		return "", err
	}
	router.Platform = platform
	for _, value := range []*string{&router.RouterID, &router.LocalIPv4, &router.LocalIPv6, &router.AS112NextHop4, &router.AS112NextHop6} {
		if *value != "" {
			ip, _ := netip.ParseAddr(*value)
			*value = ip.String()
		}
	}
	peers = enabledPeers(peers)
	for i := range peers {
		ip, _ := netip.ParseAddr(peers[i].Address)
		peers[i].Address = ip.String()
		peers[i].AllowedPrefixes = []string{}
		peers[i].AllowedRoutes = nil
	}
	version := 1
	if !historical && (platform == "bird2" || platform == "bird3" || platform == "frr") {
		version = 2
	}
	model, err := json.Marshal(as112RoutingModel{version, platform, router, peers})
	if err != nil {
		return "", err
	}
	prefix := as112Header(platform) + as112ModelLine(platform, base64.RawStdEncoding.EncodeToString(model))
	var content string
	switch platform {
	case "bird2", "bird3":
		content = renderAS112BIRD(router, peers)
	case "frr":
		content = renderAS112FRR(router, peers)
	case "openbgpd":
		content = renderAS112OpenBGPD(router, peers)
	case "junos":
		content = renderAS112Junos(router, peers)
	}
	if historical {
		content = strings.ReplaceAll(content, "  graceful restart off;\n  long lived graceful restart off;\n", "")
		if platform == "frr" {
			for _, p := range peers {
				content = strings.ReplaceAll(content, " neighbor "+p.Address+" graceful-restart-disable\n", "")
			}
		}
	}
	return boundedRendered(prefix+content, nil)
}
func as112PrefixesFor(router Router, v4 bool) []string {
	out := []string{}
	for _, raw := range AS112Service(router).Prefixes() {
		prefix, _ := netip.ParsePrefix(raw)
		if prefix.Addr().Is4() == v4 {
			out = append(out, raw)
		}
	}
	return out
}
func renderAS112BIRD(r Router, peers []Peer) string {
	var b strings.Builder
	fmt.Fprintf(&b, "router id %s;\nlog stderr { warning, error, fatal };\nprotocol device { scan time 60; }\n", r.RouterID)
	for _, v4 := range []bool{true, false} {
		prefixes := as112PrefixesFor(r, v4)
		if len(prefixes) == 0 {
			continue
		}
		family := "6"
		if v4 {
			family = "4"
		}
		fmt.Fprintf(&b, "protocol static as112_static%s {\n  ipv%s;\n", family, family)
		for _, prefix := range prefixes {
			fmt.Fprintf(&b, "  route %s blackhole;\n", prefix)
		}
		b.WriteString("}\n")
	}
	for _, p := range peers {
		ip, _ := netip.ParseAddr(p.Address)
		family, local := "6", r.LocalIPv6
		if ip.Is4() {
			family, local = "4", r.LocalIPv4
		}
		fmt.Fprintf(&b, "protocol bgp peer_%s {\n", Checksum(p.ID)[:20])
		if comment := authenticationComment(p, false); comment != "" {
			fmt.Fprintf(&b, "  # %s\n", comment)
		}
		fmt.Fprintf(&b, "  local %s as 112;\n  neighbor %s as %d;\n  enforce first as on;\n  graceful restart off;\n  long lived graceful restart off;\n", local, p.Address, p.ASN)
		if p.Password != "" {
			fmt.Fprintf(&b, "  password \"%s\";\n", p.Password)
		}
		fmt.Fprintf(&b, "  ipv%s {\n    import none;\n    receive limit %d action disable;\n    next hop self;\n    export filter {\n      if source != RTS_STATIC then reject;\n      if proto != \"as112_static%s\" then reject;\n      if net !~ [ %s ] then reject;\n      if defined(bgp_path) then { if bgp_path.len != 0 then reject; }\n      accept;\n    };\n  };\n}\n", family, p.MaxPrefixes, family, strings.Join(as112PrefixesFor(r, ip.Is4()), ", "))
	}
	return b.String()
}
func renderAS112FRR(r Router, peers []Peer) string {
	var b strings.Builder
	b.WriteString("frr defaults traditional\nhostname moedove-as112\n!\nbgp as-path access-list md_as112_local permit ^$\nroute-map md_as112_deny deny 10\n!\n")
	for _, v4 := range []bool{true, false} {
		family, suffix := "ipv6", "6"
		if v4 {
			family, suffix = "ip", "4"
		}
		prefixes := as112PrefixesFor(r, v4)
		for i, prefix := range prefixes {
			fmt.Fprintf(&b, "%s prefix-list md_as112_%s seq %d permit %s\n", family, suffix, (i+1)*5, prefix)
		}
		if len(prefixes) > 0 {
			fmt.Fprintf(&b, "route-map md_as112_export%s permit 10\n match %s address prefix-list md_as112_%s\n match as-path md_as112_local\n!\nroute-map md_as112_export%s deny 20\n!\n", suffix, family, suffix, suffix)
		}
	}
	fmt.Fprintf(&b, "router bgp 112 view MOEDOVE\n bgp router-id %s\n no bgp default ipv4-unicast\n no bgp network import-check\n", r.RouterID)
	for _, p := range peers {
		ip, _ := netip.ParseAddr(p.Address)
		local := r.LocalIPv4
		if ip.Is6() {
			local = r.LocalIPv6
		}
		if comment := authenticationComment(p, false); comment != "" {
			fmt.Fprintf(&b, " ! %s\n", comment)
		}
		fmt.Fprintf(&b, " neighbor %s remote-as %d\n neighbor %s update-source %s\n neighbor %s graceful-restart-disable\n", p.Address, p.ASN, p.Address, local, p.Address)
		if p.Password != "" {
			fmt.Fprintf(&b, " neighbor %s password %s\n", p.Address, p.Password)
		}
	}
	for _, v4 := range []bool{true, false} {
		family := "6"
		if v4 {
			family = "4"
		}
		prefixes := as112PrefixesFor(r, v4)
		if len(prefixes) == 0 {
			continue
		}
		fmt.Fprintf(&b, " address-family ipv%s unicast\n", family)
		for _, prefix := range prefixes {
			fmt.Fprintf(&b, "  network %s\n", prefix)
		}
		for _, p := range peers {
			ip, _ := netip.ParseAddr(p.Address)
			if ip.Is4() != v4 {
				continue
			}
			fmt.Fprintf(&b, "  neighbor %s activate\n  neighbor %s route-map md_as112_deny in\n  neighbor %s route-map md_as112_export%s out\n  neighbor %s next-hop-self\n  neighbor %s soft-reconfiguration inbound\n  neighbor %s maximum-prefix %d force\n", p.Address, p.Address, p.Address, family, p.Address, p.Address, p.Address, p.MaxPrefixes)
		}
		b.WriteString(" exit-address-family\n")
	}
	b.WriteString("exit\n")
	return b.String()
}
func renderAS112OpenBGPD(r Router, peers []Peer) string {
	var b strings.Builder
	fmt.Fprintf(&b, "AS 112\nrouter-id %s\nfib-update no\nreject as-set yes\nsocket \"%s\"\n", r.RouterID, OpenBGPDControlSocket)
	for _, local := range []string{r.LocalIPv4, r.LocalIPv6} {
		if local != "" {
			fmt.Fprintf(&b, "listen on %s\n", local)
		}
	}
	for _, prefix := range AS112Service(r).Prefixes() {
		fmt.Fprintf(&b, "network %s\n", prefix)
	}
	for _, p := range peers {
		ip, _ := netip.ParseAddr(p.Address)
		local, family, other := r.LocalIPv4, "inet", "inet6"
		if ip.Is6() {
			local, family, other = r.LocalIPv6, "inet6", "inet"
		}
		fmt.Fprintf(&b, "neighbor %s {\n  descr \"%s\"\n  remote-as %d\n  local-address %s\n  announce %s unicast\n  announce %s none\n  enforce neighbor-as yes\n  enforce local-as yes\n  max-prefix %d\n  set nexthop self\n", p.Address, peerName(p), p.ASN, local, family, other, p.MaxPrefixes)
		if comment := authenticationComment(p, false); comment != "" {
			fmt.Fprintf(&b, "  # %s\n", comment)
		}
		if p.Password != "" {
			fmt.Fprintf(&b, "  tcp md5sig password \"%s\"\n", p.Password)
		}
		b.WriteString("}\n")
	}
	b.WriteString("deny from any\ndeny to any\ndeny quick to any max-as-len 0\n")
	for _, prefix := range AS112Service(r).Prefixes() {
		fmt.Fprintf(&b, "allow to any prefix %s\n", prefix)
	}
	return b.String()
}
func renderAS112Junos(r Router, peers []Peer) string {
	var b strings.Builder
	key := r.ID
	if key == "" {
		key = r.RouterID
	}
	group := "moedove_" + Checksum(key)[:16]
	fmt.Fprintf(&b, "<configuration xmlns=\"\" xmlns:nc=\"%s\">\n  <groups nc:operation=\"replace\">\n    <name>%s</name>\n    <routing-options>\n", netconfNS, group)
	for _, v4 := range []bool{true, false} {
		prefixes := as112PrefixesFor(r, v4)
		if len(prefixes) == 0 {
			continue
		}
		if !v4 {
			b.WriteString("      <rib><name>inet6.0</name>\n")
		}
		b.WriteString("      <static>\n")
		for _, prefix := range prefixes {
			fmt.Fprintf(&b, "        <route><name>%s</name><discard/></route>\n", prefix)
		}
		for _, raw := range AS112Service(r).Addresses() {
			ip, _ := netip.ParseAddr(raw)
			if ip.Is4() != v4 {
				continue
			}
			bits, nextHop := 128, r.AS112NextHop6
			if v4 {
				bits, nextHop = 32, r.AS112NextHop4
			}
			fmt.Fprintf(&b, "        <route><name>%s/%d</name><next-hop>%s</next-hop></route>\n", ip, bits, nextHop)
		}
		b.WriteString("      </static>\n")
		if !v4 {
			b.WriteString("      </rib>\n")
		}
	}
	b.WriteString("    </routing-options>\n    <policy-options>\n")
	fmt.Fprintf(&b, "      <policy-statement><name>%s_deny</name><then><reject/></then></policy-statement>\n      <policy-statement><name>%s_origin</name>\n        <term><name>only_local_static_service</name><from><protocol>static</protocol>\n", group, group)
	for _, prefix := range AS112Service(r).Prefixes() {
		fmt.Fprintf(&b, "          <route-filter><address>%s</address><exact/></route-filter>\n", prefix)
	}
	b.WriteString("        </from><then><accept/></then></term>\n        <term><name>default_deny</name><then><reject/></then></term>\n      </policy-statement>\n    </policy-options>\n    <protocols><bgp>\n")
	for _, p := range peers {
		ip, _ := netip.ParseAddr(p.Address)
		local, family := r.LocalIPv4, "inet"
		if ip.Is6() {
			local, family = r.LocalIPv6, "inet6"
		}
		fmt.Fprintf(&b, "      <group>\n        <name>%s</name>\n        <type>external</type><local-address>%s</local-address>\n", peerName(p), local)
		if comment := authenticationComment(p, true); comment != "" {
			fmt.Fprintf(&b, "        <!-- %s -->\n", comment)
		}
		if p.Password != "" {
			fmt.Fprintf(&b, "        <authentication-key>%s</authentication-key>\n", p.Password)
		}
		fmt.Fprintf(&b, "        <family><%s><unicast><prefix-limit><maximum>%d</maximum><teardown><idle-timeout><forever/></idle-timeout></teardown></prefix-limit></unicast></%s></family>\n        <import>%s_deny</import><export>%s_origin</export><peer-as>%d</peer-as>\n        <neighbor><name>%s</name></neighbor>\n      </group>\n", family, p.MaxPrefixes, family, group, group, p.ASN, p.Address)
	}
	fmt.Fprintf(&b, "    </bgp></protocols>\n  </groups>\n  <apply-groups>%s</apply-groups>\n  <routing-options><router-id>%s</router-id><autonomous-system><as-number>112</as-number></autonomous-system></routing-options>\n</configuration>\n", group, r.RouterID)
	return b.String()
}

var as112BirdPeer = regexp.MustCompile(`^protocol bgp peer_([a-f0-9]{20}) \{$`)
var as112BirdSecret = regexp.MustCompile(`^password "([A-Za-z0-9+/=_-]{1,80})";$`)
var as112FRRSecret = regexp.MustCompile(`^neighbor ([0-9a-f:.]+) password ([A-Za-z0-9+/=_-]{1,80})$`)
var as112JunosSecret = regexp.MustCompile(`^<authentication-key>([A-Za-z0-9+/=_-]{1,80})</authentication-key>$`)

func parseAS112Artifact(platform, config string) (as112RoutingModel, error) {
	return parseAS112Version(platform, config, false)
}
func parseAS112Version(platform, config string, allowHistorical bool) (as112RoutingModel, error) {
	var model as112RoutingModel
	fail := func() (as112RoutingModel, error) {
		return as112RoutingModel{}, errors.New("AS112 artifact does not match the exact generated origin-only profile")
	}
	if !isAS112Artifact(platform, config) || len(config) > maxConfigSize || strings.Contains(config, RedactedBGPPassword) {
		return fail()
	}
	lines := strings.Split(config, "\n")
	if len(lines) < 3 {
		return fail()
	}
	encoded := strings.TrimPrefix(lines[1], strings.TrimSuffix(as112ModelLine(platform, ""), "\n"))
	if platform == "junos" {
		encoded = strings.TrimSuffix(strings.TrimPrefix(lines[1], "<!-- moedove-as112 "), " -->")
	} else {
		marker := "# moedove-as112 "
		if platform == "frr" {
			marker = "! moedove-as112 "
		}
		if !strings.HasPrefix(lines[1], marker) {
			return fail()
		}
		encoded = strings.TrimPrefix(lines[1], marker)
	}
	raw, err := base64.RawStdEncoding.DecodeString(encoded)
	if err != nil {
		return fail()
	}
	decoder := json.NewDecoder(strings.NewReader(string(raw)))
	decoder.DisallowUnknownFields()
	currentVersion := 1
	if platform == "bird2" || platform == "bird3" || platform == "frr" {
		currentVersion = 2
	}
	if decoder.Decode(&model) != nil || decoder.Decode(new(any)) != io.EOF || (model.Version != currentVersion && !(allowHistorical && model.Version == 1)) || model.Platform != platform {
		return fail()
	}
	byAddress, byBird, byJunos := map[string]int{}, map[string]int{}, map[string]int{}
	for i, p := range model.Peers {
		byAddress[p.Address] = i
		byBird[Checksum(p.ID)[:20]] = i
		byJunos[peerName(p)] = i
	}
	current := -1
	seen := map[int]bool{}
	set := func(i int, password string) bool {
		if i < 0 || i >= len(model.Peers) || seen[i] {
			return false
		}
		seen[i] = true
		model.Peers[i].Password = password
		return true
	}
	for _, rawLine := range lines[2:] {
		line := strings.TrimSpace(rawLine)
		switch platform {
		case "bird2", "bird3":
			if m := as112BirdPeer.FindStringSubmatch(line); m != nil {
				var ok bool
				current, ok = byBird[m[1]]
				if !ok {
					return fail()
				}
			}
			if m := as112BirdSecret.FindStringSubmatch(line); m != nil && !set(current, m[1]) {
				return fail()
			}
		case "frr":
			if m := as112FRRSecret.FindStringSubmatch(line); m != nil {
				i, ok := byAddress[m[1]]
				if !ok || !set(i, m[2]) {
					return fail()
				}
			}
		case "openbgpd":
			if m := openBGPDNeighbor.FindStringSubmatch(line); m != nil {
				var ok bool
				current, ok = byAddress[m[1]]
				if !ok {
					return fail()
				}
			}
			if m := openBGPDPassword.FindStringSubmatch("  " + line); m != nil && !set(current, m[1]) {
				return fail()
			}
		case "junos":
			if strings.HasPrefix(line, "<name>") && strings.HasSuffix(line, "</name>") {
				if i, ok := byJunos[strings.TrimSuffix(strings.TrimPrefix(line, "<name>"), "</name>")]; ok {
					current = i
				}
			}
			if m := as112JunosSecret.FindStringSubmatch(line); m != nil && !set(current, m[1]) {
				return fail()
			}
		}
	}
	wanted, err := renderAS112Version(platform, model.Router, model.Peers, model.Version == 1 && currentVersion == 2)
	if err != nil || wanted != config {
		return fail()
	}
	return model, nil
}
func redactAS112(platform, config string) (string, error) {
	model, err := parseAS112Version(platform, config, true)
	if err != nil {
		return "", errUnsafeRedaction
	}
	for _, p := range model.Peers {
		if p.Password == "" {
			continue
		}
		var old, next string
		switch platform {
		case "bird2", "bird3":
			old = "password \"" + p.Password + "\";"
			next = "password \"" + RedactedBGPPassword + "\";"
		case "frr":
			old = "neighbor " + p.Address + " password " + p.Password
			next = "neighbor " + p.Address + " password " + RedactedBGPPassword
		case "openbgpd":
			old = "tcp md5sig password \"" + p.Password + "\""
			next = "tcp md5sig password \"" + RedactedBGPPassword + "\""
		case "junos":
			old = "<authentication-key>" + p.Password + "</authentication-key>"
			next = "<authentication-key>" + RedactedBGPPassword + "</authentication-key>"
		}
		config = strings.ReplaceAll(config, old, next)
	}
	return config, nil
}
