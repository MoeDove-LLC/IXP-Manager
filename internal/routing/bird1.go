const bird1Header = "# Generated by MoeDove IXP Manager; managed BIRD 1 single-family profile.\n"
const bird1ModelPrefix = "# moedove-bird1-model "

type bird1Model struct {
	Version int    `json:"version"`
	Family  int    `json:"family"`
	Router  Router `json:"router"`
	Peers   []Peer `json:"peers"`
}

// RenderBIRD1 emits BIRD 1 syntax directly. It never strips channel blocks from
// a BIRD 2 artifact. One reviewed router describes exactly one daemon/family.
// The model comment is secret-free and permits exact generated-profile checks.
func RenderBIRD1(router Router, peers []Peer) (string, error) {
	return renderBIRD1Version(router, peers, 2)
}
func renderBIRD1Version(router Router, peers []Peer, version int) (string, error) {
	if version != 1 && version != 2 {
		return "", errors.New("unsupported BIRD1 profile version")
	}
	role, policy, e := normalizedRole(router)
	if e != nil {
		return "", e
	}
	if role != RoleRouteServer && role != RoleRouteCollector {
		return "", errors.New("BIRD 1 supports only the dedicated route-server and route-collector profiles")
	}
	if router.RPKI != nil {
		return "", errors.New("BIRD 1 has no verified runtime RPKI adapter")
	}
	if router.RFC1997Passthrough != nil {
		return "", errors.New("BIRD 1 RFC1997 passthrough control is not verified; no implicit policy substitution")
	}
	if (router.LocalIPv4 == "") == (router.LocalIPv6 == "") {
		return "", errors.New("BIRD 1 requires exactly one local address family; create separate IPv4 bird and IPv6 bird6 router instances")
	}
	// Reuse the existing typed input checks only, never their generated output.
	if _, e = Render(router, peers); e != nil {
		return "", e
	}
	family := 4
	local := router.LocalIPv4
	if local == "" {
		family = 6
		local = router.LocalIPv6
	}
	router.Role, router.CollectorPolicy, router.Platform = role, policy, "bird1"
	for _, value := range []*string{&router.RouterID, &router.LocalIPv4, &router.LocalIPv6} {
		if *value != "" {
			ip, _ := netip.ParseAddr(*value)
			*value = ip.String()
		}
	}
	localIP, _ := netip.ParseAddr(local)
	local = localIP.String()
	peers = enabledPeers(peers)
	for i := range peers {
		p := &peers[i]
		ip, _ := netip.ParseAddr(p.Address)
		if ip.Is4() != (family == 4) {
			return "", errors.New("BIRD 1 peers must match the instance's single address family")
		}
		p.Address = ip.String()
		p.AllowedPrefixes = canonicalPrefixes(*p)
		pairs := []PrefixOrigin{}
		seen := map[string]bool{}
		for _, pair := range p.AllowedRoutes {
			prefix, _ := netip.ParsePrefix(pair.Prefix)
			pair.Prefix = prefix.String()
			key := fmt.Sprintf("%s/%d", pair.Prefix, pair.OriginASN)
			if !seen[key] {
				seen[key] = true
				pairs = append(pairs, pair)
			}
		}
		sort.Slice(pairs, func(i, j int) bool {
			if pairs[i].Prefix != pairs[j].Prefix {
				return pairs[i].Prefix < pairs[j].Prefix
			}
			return pairs[i].OriginASN < pairs[j].OriginASN
		})
		p.AllowedRoutes = pairs
	}
	raw, e := json.Marshal(bird1Model{Version: version, Family: family, Router: router, Peers: peers})
	if e != nil {
		return "", e
	}
	var b strings.Builder
	b.WriteString(bird1Header)
	b.WriteString(bird1ModelPrefix + base64.RawURLEncoding.EncodeToString(raw) + "\n")
	fmt.Fprintf(&b, "router id %s;\nlog stderr { warning, error, fatal };\nlisten bgp address %s;\nprotocol device { scan time 60; }\n\n", router.RouterID, local)
	collector := role == RoleRouteCollector
	for _, p := range peers {
		if comment := authenticationComment(p, false); comment != "" {
			fmt.Fprintf(&b, "# %s\n", comment)
		}
		fmt.Fprintf(&b, "protocol bgp peer_%s {\n  local as %d;\n  source address %s;\n  neighbor %s as %d;\n", Checksum(p.ID)[:20], router.ASN, local, p.Address, p.ASN)
		if !collector {
			b.WriteString("  rs client;\n  next hop keep;\n")
			if family == 6 {
				b.WriteString("  missing lladdr ignore;\n")
			}
		}
		if p.Password != "" {
			fmt.Fprintf(&b, "  password \"%s\";\n", p.Password)
		}
		if collector && policy == CollectorObserve {
			b.WriteString("  import keep filtered yes;\n")
		}
		fmt.Fprintf(&b, "  import filter {\n    if bgp_path.len = 0 then reject;\n    if bgp_path.len > 64 then reject;\n    if bgp_path.first != %d then reject;\n    if from != bgp_next_hop then reject;\n", p.ASN)
		if len(p.AllowedPrefixes) == 0 {
			b.WriteString("    reject;\n")
		} else {
			fmt.Fprintf(&b, "    if net !~ [ %s ] then reject;\n", strings.Join(p.AllowedPrefixes, ", "))
			b.WriteString(strings.ReplaceAll(birdOriginGuard(p), "      ", "    "))
			b.WriteString("    accept;\n")
		}
		fmt.Fprintf(&b, "  };\n  import limit %d action block;\n", p.MaxPrefixes)
		if collector {
			if policy == CollectorObserve {
				fmt.Fprintf(&b, "  receive limit %d action disable;\n", p.MaxPrefixes)
			}
			b.WriteString("  export none;\n")
		} else {
			b.WriteString("  export filter {\n    if source != RTS_BGP then reject;\n    accept;\n  };\n")
		}
		b.WriteString("}\n\n")
	}
	config := b.String()
	if version == 2 {
		marker := "define md_managed_checksum = \"" + Checksum(config) + "\";\n"
		config = strings.Replace(config, "router id ", marker+"router id ", 1)
	}
	return boundedRendered(config, nil)
}

var bird1PeerLine = regexp.MustCompile(`^protocol bgp peer_([a-f0-9]{20}) \{$`)
var bird1SecretLine = regexp.MustCompile(`^  password "([A-Za-z0-9+/=_-]{1,80})";$`)

func parseManagedBIRD1(config string) (bird1Model, error) {
	var model bird1Model
	fail := func() (bird1Model, error) {
		return bird1Model{}, errors.New("configuration is not an exact managed BIRD 1 single-family profile; raw content withheld")
	}
	if len(config) == 0 || len(config) > maxConfigSize || !strings.HasPrefix(config, bird1Header+bird1ModelPrefix) || strings.Contains(config, RedactedBGPPassword) {
		return fail()
	}
	lines := strings.Split(config, "\n")
	raw, e := base64.RawURLEncoding.DecodeString(strings.TrimPrefix(lines[1], bird1ModelPrefix))
	if e != nil {
		return fail()
	}
	d := json.NewDecoder(strings.NewReader(string(raw)))
	d.DisallowUnknownFields()
	if d.Decode(&model) != nil || d.Decode(new(any)) != io.EOF || (model.Version != 1 && model.Version != 2) || (model.Family != 4 && model.Family != 6) {
		return fail()
	}
	byProtocol := map[string]int{}
	for i, p := range model.Peers {
		key := Checksum(p.ID)[:20]
		if _, ok := byProtocol[key]; ok {
			return fail()
		}
		byProtocol[key] = i
	}
	current := ""
	secrets := map[string]bool{}
	for _, line := range lines[2:] {
		if match := bird1PeerLine.FindStringSubmatch(line); match != nil {
			current = match[1]
		}
		if line == "}" {
			current = ""
		}
		if strings.HasPrefix(strings.TrimSpace(line), "password") {
			match := bird1SecretLine.FindStringSubmatch(line)
			index, exists := byProtocol[current]
			if match == nil || !exists || secrets[current] {
				return fail()
			}
			secrets[current] = true
			model.Peers[index].Password = match[1]
		}
	}
	want, e := renderBIRD1Version(model.Router, model.Peers, model.Version)
	if e != nil || want != config {
		return fail()
	}
	return model, nil
}
func ValidateManagedBIRD1(config string) error { _, e := parseManagedBIRD1(config); return e }

// BIRD1Family returns the pinned address family only after exact reconstruction;
// a comment alone cannot select which privileged native checker gets called.
func BIRD1Family(config string) (int, error) {
	model, e := parseManagedBIRD1(config)
	return model.Family, e
}
func RedactBIRD1(config string) (string, error) {
	if _, e := parseManagedBIRD1(config); e != nil {
		return "", e
	}
	lines := strings.Split(config, "\n")
	for i, line := range lines {
		if strings.HasPrefix(line, "define md_managed_checksum = ") {
			lines[i] = "define md_managed_checksum = \"[REDACTED-RUNTIME-DIGEST]\";"
			continue
		}
		if bird1SecretLine.MatchString(line) {
			lines[i] = "  password \"" + RedactedBGPPassword + "\";"
		}
	}
	return strings.Join(lines, "\n"), nil
}

// The runtime digest binds all canonical bytes except its own definition. It
// may expose a secret-guessing oracle and must never appear in public previews.
func bird1RuntimeFingerprint(config string) (string, error) {
	model, e := parseManagedBIRD1(config)
	if e != nil {
		return "", e
	}
	if model.Version != 2 {
		return "", errors.New("BIRD 1 automatic apply requires a reviewed v2 profile with runtime readback binding; legacy v1 remains preview/check only")
	}
	line := strings.Split(config, "\n")[2]
	value := strings.TrimSuffix(strings.TrimPrefix(line, "define md_managed_checksum = \""), "\";")
	if len(value) != 64 {
		return "", errors.New("BIRD 1 runtime fingerprint missing")
	}
	return value, nil
}
