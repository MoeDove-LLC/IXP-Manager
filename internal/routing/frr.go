func enabledPeers(peers []Peer) []Peer {
	out := []Peer{}
	for _, p := range peers {
		if p.Enabled {
			out = append(out, p)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}
func peerName(p Peer) string { return "md_" + Checksum(p.ID)[:16] }
func canonicalPrefixes(p Peer) []string {
	seen := map[string]bool{}
	out := []string{}
	for _, raw := range p.AllowedPrefixes {
		prefix, _ := netip.ParsePrefix(raw)
		s := prefix.String()
		if !seen[s] {
			out = append(out, s)
			seen[s] = true
		}
	}
	sort.Strings(out)
	return out
}

// renderFRR generates a dedicated BGP view: no route is installed in the kernel,
// no network or redistribution command can introduce unrelated local routes.
func renderFRR(router Router, peers []Peer) string {
	peers = enabledPeers(peers)
	var b strings.Builder
	b.WriteString("! Generated by MoeDove IXP Manager; dedicated route-server view.\nfrr defaults traditional\nhostname moedove-rs\n!\n")
	rpki, _ := normalizeRPKI(router.RPKI)
	if rpki != nil {
		fmt.Fprintf(&b, "rpki\n rpki polling_period 30\n rpki retry_interval 5\n rpki expire_interval %d\n rpki cache tcp %s %d preference 1\nexit\n!\n", rpki.ExpireSeconds, rpki.Host, rpki.Port)
	}
	for _, p := range peers {
		name := peerName(p)
		ip, _ := netip.ParseAddr(p.Address)
		family := "ip"
		if ip.Is6() {
			family = "ipv6"
		}
		for i, prefix := range canonicalPrefixes(p) {
			fmt.Fprintf(&b, "%s prefix-list %s seq %d permit %s\n", family, name, (i+1)*5, prefix)
		}
		fmt.Fprintf(&b, "bgp as-path access-list %s permit ^%d(_[0-9]+){0,63}$\n!\n", name, p.ASN)
		for _, group := range originGroups(p) {
			if group.ASN == 0 {
				continue
			}
			for i, prefix := range group.Prefixes {
				fmt.Fprintf(&b, "%s prefix-list %s seq %d permit %s\n", family, group.Name, (i+1)*5, prefix)
			}
			fmt.Fprintf(&b, "bgp as-path access-list %s permit %s\n!\n", group.Name, frrOriginPattern(p.ASN, group.ASN))
		}

	}
	// The same policy is safe whether FRR applies it as a normal inbound filter
	// or as a route-server Loc-RIB import policy: only explicitly authorized
	// prefix / origin-neighbor-AS combinations can enter a client Loc-RIB.
	sequence := 10
	for _, p := range peers {
		ip, _ := netip.ParseAddr(p.Address)
		family := "ip"
		if ip.Is6() {
			family = "ipv6"
		}
		for _, group := range originGroups(p) {
			for _, policy := range []string{"md_ingress", "md_authorized"} {
				fmt.Fprintf(&b, "route-map %s permit %d\n", policy, sequence)
				if policy == "md_ingress" {
					fmt.Fprintf(&b, " match peer %s\n", ip)
				}
				fmt.Fprintf(&b, " match %s address prefix-list %s\n match as-path %s\n", family, group.Name, group.Name)
				if rpki != nil {
					b.WriteString(" match rpki valid\n")
				}
				b.WriteString("!\n")
			}
			sequence += 10
		}
	}
	fmt.Fprintf(&b, "route-map md_ingress deny %d\n!\nroute-map md_authorized deny %d\n!\nrouter bgp %d view MOEDOVE\n bgp router-id %s\n no bgp default ipv4-unicast\n", sequence, sequence, router.ASN, router.RouterID)
	for _, p := range peers {
		ip, _ := netip.ParseAddr(p.Address)
		local := router.LocalIPv4
		if ip.Is6() {
			local = router.LocalIPv6
		}
		if comment := authenticationComment(p, false); comment != "" {
			fmt.Fprintf(&b, " ! %s\n", comment)
		}
		fmt.Fprintf(&b, " neighbor %s remote-as %d\n neighbor %s update-source %s\n", ip, p.ASN, ip, local)
		if p.Password != "" {
			fmt.Fprintf(&b, " neighbor %s password %s\n", ip, p.Password)
		}
	}
	for _, ipv4 := range []bool{true, false} {
		family := "ipv6"
		if ipv4 {
			family = "ipv4"
		}
		fmt.Fprintf(&b, " address-family %s unicast\n", family)
		for _, p := range peers {
			ip, _ := netip.ParseAddr(p.Address)
			if ip.Is4() != ipv4 {
				continue
			}
			if rpki != nil {
				fmt.Fprintf(&b, "  neighbor %s soft-reconfiguration inbound\n", ip)
			}
			name := peerName(p)
			force := ""
			if rpki != nil {
				force = " force"
			}
			fmt.Fprintf(&b, "  neighbor %s activate\n  neighbor %s route-server-client\n  neighbor %s prefix-list %s in\n  neighbor %s filter-list %s in\n  neighbor %s route-map md_ingress in\n  neighbor %s route-map md_authorized out\n  neighbor %s maximum-prefix %d%s\n", ip, ip, ip, name, ip, name, ip, ip, ip, p.MaxPrefixes, force)
		}
		b.WriteString(" exit-address-family\n")
	}
	b.WriteString("exit\n!\n")
	return b.String()
}

func validateFRR(ctx context.Context, binary, config string) error {
	if err := rejectRedactedArtifact(config); err != nil {
		return err
	}
	if len(config) == 0 || len(config) > maxConfigSize {
		return errors.New("configuration is empty or exceeds 16 MiB")
	}
	if binary == "" {
		binary = "bgpd"
	}
	ctx, cancel := context.WithTimeout(ctx, 15*time.Second)
	defer cancel()
	version, err := run(ctx, binary, "--version")
	if err != nil {
		return nativeFailure("FRR bgpd executable unavailable", err)
	}
	if !regexp.MustCompile(`(?m)^bgpd version (?:[8-9]|[1-9][0-9]+)\.`).MatchString(version) {
		return errors.New("validation requires the FRRouting bgpd executable")
	}
	f, err := os.CreateTemp("", "moedove-frr-*.conf")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err = f.WriteString(config); err != nil {
		f.Close()
		return err
	}
	if err = f.Close(); err != nil {
		return err
	}
	args := []string{"--dryrun", "--skip_runas", "--bgp_port", "0", "--no_zebra", "--no_kernel", "--vty_socket", os.TempDir(), "--pid_file", f.Name() + ".pid", "--config_file", f.Name()}
	usesRPKI := false
	for _, line := range strings.Split(config, "\n") {
		if strings.TrimSpace(line) == "rpki" || strings.HasPrefix(strings.TrimSpace(line), "match rpki ") {
			usesRPKI = true
		}
	}
	if usesRPKI {
		args = append(args, "-M", "rpki")
		if moduleDir := os.Getenv("MOEDOVE_FRR_MODULE_DIR"); moduleDir != "" {
			if !filepath.IsAbs(moduleDir) || filepath.Clean(moduleDir) != moduleDir {
				return errors.New("FRR module directory must be absolute and clean")
			}
			args = append(args, "--moduledir", moduleDir)
		}
	}
	output, err := runNative(ctx, binary, args, usesRPKI)
	if err != nil && usesRPKI {
		return nativeFailure("network-isolated FRR RPKI validation failed (requires user/network namespaces and rpki module)", err)
	}
	if err != nil {
		return nativeFailure("FRR native dry-run rejected configuration", err)
	}
	// Some FRR versions log rejected VTY lines but still exit zero in dry-run.
	if usesRPKI {
		// RTRlib starts during parse even with -C. In the mandatory private
		// network namespace these specific transport diagnostics are expected;
		// command/syntax/initialization errors remain fatal below.
		transport := regexp.MustCompile(`^\([^\r\n]+\): (RTR_MGR: (rtr_mgr_start\(\)|Group\([0-9]+\) status changed to: RTR_MGR_ERROR|No other inactive groups found)|RTR Socket: (State: RTR_(CONNECTING|ERROR_TRANSPORT)|Waiting [0-9]+)|TCP Transport\([^\r\n]+\): (Couldn't establish TCP connection, Network is unreachable|Socket closed))$`)
		lines := []string{}
		for _, line := range strings.Split(output, "\n") {
			if !transport.MatchString(line) {
				lines = append(lines, line)
			}
		}
		output = strings.Join(lines, "\n")
	}
	lowered := strings.ToLower(output)
	for _, marker := range []string{"unknown command", "ambiguous command", "no such command", "error", "failed", "failure"} {
		if strings.Contains(lowered, marker) {
			return errors.New("FRR dry-run reported an error; raw diagnostics withheld")
		}
	}
	return nil
}
