const bird2ServerHeader = "# Generated by MoeDove IXP Manager. BIRD 2; exact prefix allowlists.\n"
const bird2CollectorHeader = "# Generated by MoeDove IXP Manager. BIRD 2; route collector.\n"
const bird3ServerHeader = "# Generated by MoeDove IXP Manager. BIRD 3; exact prefix allowlists.\n"
const bird3CollectorHeader = "# Generated by MoeDove IXP Manager. BIRD 3; route collector.\n"

// RenderBIRD3 uses the constrained policy language shared by BIRD 2 and 3,
// verified separately against BIRD 3. Native validation NEVER falls back to 2.
func RenderBIRD3(router Router, peers []Peer) (string, error) {
	if router.Role == RoleAS112 {
		return renderAS112("bird3", router, peers)
	}
	if rpki, err := normalizeRPKI(router.RPKI); err != nil {
		return "", err
	} else if rpki != nil && rpki.ExpireSeconds < 600 {
		return "", errors.New("BIRD 3 RPKI expiry must be at least 600 seconds")
	}
	config, err := Render(router, peers)
	if err != nil {
		return "", err
	}
	if strings.HasPrefix(config, bird2ServerHeader) {
		return boundedRendered(bird3ServerHeader+strings.TrimPrefix(config, bird2ServerHeader), nil)
	}
	if strings.HasPrefix(config, bird2CollectorHeader) {
		return boundedRendered(bird3CollectorHeader+strings.TrimPrefix(config, bird2CollectorHeader), nil)
	}
	return "", errors.New("unrecognized generated BIRD policy format")
}

func ValidateBIRD3(ctx context.Context, binary, config string) error {
	return validateBIRDMajor(ctx, binary, config, 3)
}

// RedactBIRD3 recognizes only our versioned generated subset. Reusing the
// strict parser does not imply native validation with a different major version.
func RedactBIRD3(config string) (string, error) {
	if isAS112Artifact("bird3", config) {
		return redactAS112("bird3", config)
	}
	oldHeader, newHeader := "", ""
	switch {
	case strings.HasPrefix(config, bird3ServerHeader):
		oldHeader, newHeader = bird3ServerHeader, bird2ServerHeader
	case strings.HasPrefix(config, bird3CollectorHeader):
		oldHeader, newHeader = bird3CollectorHeader, bird2CollectorHeader
	default:
		return "", errUnsafeRedaction
	}
	preview, err := RedactConfig("bird2", newHeader+strings.TrimPrefix(config, oldHeader))
	if err != nil {
		return "", err
	}
	return oldHeader + strings.TrimPrefix(preview, newHeader), nil
}

func birdMajor(major int) (int, error) {
	if major == 0 {
		return 2, nil
	}
	if major != 2 && major != 3 {
		return 0, errors.New("BIRD major version must be explicitly supported (2 or 3)")
	}
	return major, nil
}

// The parser executable and the live socket may point at different versions.
// BIRD 3.4 nest/cmds.c reports its version in 1000 and ready state in 0013.
// Raw control output is never returned because it may quote private material.
func requireBIRD3Daemon(ctx context.Context, opts ApplyOptions) error {
	ctx, cancel := context.WithTimeout(ctx, 15*time.Second)
	defer cancel()
	binary := opts.BirdcBinary
	if binary == "" {
		binary = "birdc"
	}
	args := []string{"-v"}
	if opts.Socket != "" {
		args = append(args, "-s", opts.Socket)
	}
	args = append(args, "show", "status")
	output, err := run(ctx, binary, args...)
	if err != nil {
		return nativeFailure("BIRD 3 daemon identity check failed", err)
	}
	versions := 0
	ready := false
	for _, line := range strings.Split(output, "\n") {
		if strings.HasPrefix(line, "1000-") || strings.HasPrefix(line, "1000 ") {
			match := birdVersionLine.FindStringSubmatch(line[5:])
			if match == nil || match[1] != "3" {
				return errors.New("control socket does not identify a BIRD 3 daemon")
			}
			versions++
		}
		if line == "0013 Daemon is up and running" {
			ready = true
		}
		if len(line) >= 4 && line[0] >= '8' && line[0] <= '9' {
			return errors.New("BIRD 3 daemon identity query was rejected; raw diagnostics withheld")
		}
	}
	if versions != 1 || !ready {
		return errors.New("BIRD 3 daemon identity or ready status could not be verified")
	}
	return nil
}

func validateBIRDArtifactMajor(config string, major int) error {
	if strings.HasPrefix(config, bird1Header) {
		return errors.New("generated artifact targets BIRD 1, not the selected BIRD major")
	}
	if isAS112Artifact("bird2", config) || isAS112Artifact("bird3", config) {
		platform := fmt.Sprintf("bird%d", major)
		if !isAS112Artifact(platform, config) {
			return errors.New("AS112 artifact targets a different BIRD major version")
		}
		_, err := parseAS112Artifact(platform, config)
		return err
	}
	if (major != 2 && (strings.HasPrefix(config, bird2ServerHeader) || strings.HasPrefix(config, bird2CollectorHeader))) || (major != 3 && (strings.HasPrefix(config, bird3ServerHeader) || strings.HasPrefix(config, bird3CollectorHeader))) {
		return errors.New("generated artifact targets a different BIRD major version")
	}
	return nil
}
