// The local agent accepts only collector profiles whose activated address
// families retain the export deny and observation quota mechanisms. Native
// parsing still verifies command placement and actual platform support.
func validateFRRCollectorShape(config string) error {
	lines := strings.Split(config, "\n")
	if len(lines) < 2 {
		return errors.New("collector policy marker missing")
	}
	policy := strings.TrimPrefix(lines[1], "! moedove-role role=route-collector policy=")
	if policy != CollectorObserve && policy != CollectorAuthorizedOnly {
		return errors.New("collector policy marker invalid")
	}
	family := ""
	active, inbound, outbound, soft, forced := map[string]bool{}, map[string]bool{}, map[string]bool{}, map[string]bool{}, map[string]bool{}
	source := map[string]bool{}
	deny := false
	noDefaultActivation := false
	for _, raw := range lines {
		line := strings.TrimSpace(raw)
		if line == "route-map md_collect_export deny 10" {
			deny = true
		}
		if line == "no bgp default ipv4-unicast" {
			noDefaultActivation = true
		}
		if strings.Contains(line, "route-server-client") || strings.HasPrefix(line, "route-map md_authorized ") {
			return errors.New("collector may not use route-server export policies")
		}
		fields := strings.Fields(line)
		if len(fields) == 3 && fields[0] == "address-family" {
			family = fields[1]
		}
		if line == "exit-address-family" {
			family = ""
		}
		if len(fields) < 3 || fields[0] != "neighbor" {
			continue
		}
		key := family + "/" + fields[1]
		switch fields[2] {
		case "enforce-first-as":
			source[fields[1]] = true
		case "activate":
			active[key] = true
		case "soft-reconfiguration":
			soft[key] = true
		case "maximum-prefix":
			if len(fields) == 5 && fields[4] == "force" {
				forced[key] = true
			}
		case "route-map":
			if len(fields) == 5 && fields[4] == "in" {
				if fields[3] != "md_ingress" {
					return errors.New("collector inbound policy must use its explicit authorized route map")
				}
				inbound[key] = true
			}
			if len(fields) == 5 && fields[4] == "out" {
				if fields[3] != "md_collect_export" {
					return errors.New("collector outbound policy must deny every route")
				}
				outbound[key] = true
			}
		}
	}
	if !deny || !noDefaultActivation {
		return errors.New("collector requires export deny and disabled implicit IPv4 activation")
	}
	for key := range active {
		parts := strings.SplitN(key, "/", 2)
		if !inbound[key] || !outbound[key] || !source[parts[1]] {
			return errors.New("collector requires ingress policy, export deny and explicit first-AS enforcement for every active peer")
		}
		if (policy == CollectorObserve || soft[key]) && (!soft[key] || !forced[key]) {
			return errors.New("observation requires inbound retention and a maximum covering filtered routes")
		}
	}
	return nil
}

// Observation keeps policy-rejected routes separately; accepting a route into
// the authorized RIB never implies it may be exported by a collector.
func writeBIRDCollectorPeer(b *strings.Builder, policy string, peer Peer, protocol, local string, localASN uint32, remote, authentication, family, channel, checks string, prefixes []string) {
	// RPKI re-evaluation also needs a pre-policy cache. Every collector cache
	// must have a limit including filtered routes, even in authorized-only mode.
	retained := policy == CollectorObserve || channel != ""
	if retained {
		if channel == "" {
			channel = "    import table yes;\n"
		}
		channel += "    import keep filtered yes;\n"
	}
	fmt.Fprintf(b, "protocol bgp %s {\n  local %s as %d;\n  neighbor %s as %d;\n  enforce first as on;\n%s  %s {\n%s    import filter {\n      if bgp_path.len = 0 then reject;\n      if bgp_path.len > 64 then reject;\n      if bgp_path.first != %d then reject;\n", protocol, local, localASN, remote, peer.ASN, authentication, family, channel, peer.ASN)
	if len(prefixes) == 0 {
		b.WriteString("      reject;\n")
	} else {
		fmt.Fprintf(b, "      if net !~ [ %s ] then reject;\n%s      accept;\n", strings.Join(prefixes, ", "), checks)
	}
	fmt.Fprintf(b, "    };\n    import limit %d action block;\n", peer.MaxPrefixes)
	if retained {
		// Unlike import limit, receive limit includes kept filtered routes. A
		// disable action also stops growth of the pre-policy import table.
		fmt.Fprintf(b, "    receive limit %d action disable;\n", peer.MaxPrefixes)
	}
	b.WriteString("    export none;\n  };\n}\n\n")
}

func renderFRRCollector(router Router, peers []Peer, policy string) string {
	peers = enabledPeers(peers)
	var b strings.Builder
	fmt.Fprintf(&b, "! Generated by MoeDove IXP Manager; dedicated route-collector view.\n! moedove-role role=route-collector policy=%s\nfrr defaults traditional\nhostname moedove-rc\n!\n", policy)
	rpki, _ := normalizeRPKI(router.RPKI)
	if rpki != nil {
		fmt.Fprintf(&b, "rpki\n rpki polling_period 30\n rpki retry_interval 5\n rpki expire_interval %d\n rpki cache tcp %s %d preference 1\nexit\n!\n", rpki.ExpireSeconds, rpki.Host, rpki.Port)
	}
	sequence := 10
	for _, peer := range peers {
		ip, _ := netip.ParseAddr(peer.Address)
		family := "ip"
		if ip.Is6() {
			family = "ipv6"
		}
		// An empty observation allowlist means deny all in the authorized RIB;
		// soft-reconfiguration retains the received prefixes for inspection.
		if len(peer.AllowedPrefixes) == 0 {
			continue
		}
		for _, group := range originGroups(peer) {
			for i, prefix := range group.Prefixes {
				fmt.Fprintf(&b, "%s prefix-list %s seq %d permit %s\n", family, group.Name, (i+1)*5, prefix)
			}
			pattern := fmt.Sprintf("^%d(_[0-9]+){0,63}$", peer.ASN)
			if group.ASN != 0 {
				pattern = frrOriginPattern(peer.ASN, group.ASN)
			}
			fmt.Fprintf(&b, "bgp as-path access-list %s permit %s\n!\nroute-map md_ingress permit %d\n match peer %s\n match %s address prefix-list %s\n match as-path %s\n", group.Name, pattern, sequence, ip, family, group.Name, group.Name)
			if rpki != nil {
				b.WriteString(" match rpki valid\n")
			}
			b.WriteString("!\n")
			sequence += 10
		}
	}
	fmt.Fprintf(&b, "route-map md_ingress deny %d\n!\nroute-map md_collect_export deny 10\n!\nrouter bgp %d view MOEDOVE\n bgp router-id %s\n no bgp default ipv4-unicast\n", sequence, router.ASN, router.RouterID)
	for _, peer := range peers {
		ip, _ := netip.ParseAddr(peer.Address)
		local := router.LocalIPv4
		if ip.Is6() {
			local = router.LocalIPv6
		}
		if comment := authenticationComment(peer, false); comment != "" {
			fmt.Fprintf(&b, " ! %s\n", comment)
		}
		fmt.Fprintf(&b, " neighbor %s remote-as %d\n neighbor %s update-source %s\n neighbor %s enforce-first-as\n", ip, peer.ASN, ip, local, ip)
		if peer.Password != "" {
			fmt.Fprintf(&b, " neighbor %s password %s\n", ip, peer.Password)
		}
	}
	for _, v4 := range []bool{true, false} {
		family := "ipv6"
		if v4 {
			family = "ipv4"
		}
		fmt.Fprintf(&b, " address-family %s unicast\n", family)
		for _, peer := range peers {
			ip, _ := netip.ParseAddr(peer.Address)
			if ip.Is4() != v4 {
				continue
			}
			if policy == CollectorObserve || rpki != nil {
				fmt.Fprintf(&b, "  neighbor %s soft-reconfiguration inbound\n", ip)
			}
			force := ""
			if policy == CollectorObserve || rpki != nil {
				force = " force"
			}
			fmt.Fprintf(&b, "  neighbor %s activate\n  neighbor %s route-map md_ingress in\n  neighbor %s route-map md_collect_export out\n  neighbor %s maximum-prefix %d%s\n", ip, ip, ip, ip, peer.MaxPrefixes, force)
		}
		b.WriteString(" exit-address-family\n")
	}
	b.WriteString("exit\n!\n")
	return b.String()
}
