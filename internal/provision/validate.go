// Validate never loads/reloads a service. Monitoring snippets stay structural:
// checking some unrelated installed main config would not validate this draft.
func Validate(ctx context.Context, a Artifact, options ValidatorOptions) (Validation, error) {
	if err := ValidateArtifact(a); err != nil {
		return Validation{}, err
	}
	switch a.Kind {
	case "as112-dns":
		return validateAS112DNS(ctx, a, options)
	case "dns-arpa":
		binary := options.NamedCheckzone
		if binary == "" {
			binary = "named-checkzone"
		}
		ctx, cancel := context.WithTimeout(ctx, 15*time.Second)
		defer cancel()
		file, err := os.CreateTemp("", "moedove-zone-*.zone")
		if err != nil {
			return Validation{}, err
		}
		defer os.Remove(file.Name())
		if _, err = io.WriteString(file, a.Content); err != nil {
			file.Close()
			return Validation{}, err
		}
		if err = file.Close(); err != nil {
			return Validation{}, err
		}
		if _, err = command(ctx, binary, "-i", "local", a.Zone, file.Name()); err != nil {
			return Validation{}, fmt.Errorf("named-checkzone unavailable or rejected the complete zone: %w", err)
		}
		return Validation{Level: "native", Message: "named-checkzone parsed this complete zone; delegation and activation were not tested"}, nil
	case "nagios", "smokeping":
		return Validation{Level: "structural", Message: "Generated include structure checked only; the target's full configuration must be verified before activation"}, nil
	case "switch-core":
		return Validation{Level: "structural", Message: "Typed switch core JSON plan checked; vendor translation, target validation and activation are still required"}, nil
	}
	return Validation{}, errors.New("unsupported provisioning kind")
}

var soaStart = regexp.MustCompile(`^@ IN SOA ([a-z0-9.-]+\.) ([a-z0-9.-]+\.) \($`)
var soaNumber = regexp.MustCompile(`^([0-9]+) ; (serial|refresh|retry|expire|minimum)$`)
var nagiosHostName = regexp.MustCompile(`^md_(member|switch|router)_[a-f0-9]{20}$`)
var nagiosCheck = regexp.MustCompile(`^check_moedove_(ping[46]|ping_busy[46]|bgp![A-Za-z0-9_-]{1,128}|router![A-Za-z0-9_-]{1,128}|switch![A-Za-z0-9_-]{1,128}|core![A-Za-z0-9_-]{1,128})$`)

func ValidateArtifact(a Artifact) error {
	if len(a.Content) == 0 || len(a.Content) > MaxArtifactBytes || strings.ContainsAny(a.Content, "\x00\r") || a.Filename == "" || filepath.Base(a.Filename) != a.Filename || strings.ContainsAny(a.Filename, "/\\\r\n\x00") {
		return errors.New("invalid artifact name, size or control characters")
	}
	switch a.Kind {
	case "as112-dns":
		if !a.Complete || a.ValidationLevel != "native" || a.Zone != "" {
			return errors.New("invalid AS112 artifact metadata")
		}
		_, err := as112.Decode(a.Content)
		return err
	case "dns-arpa":
		return checkDNSArtifact(a)
	case "nagios":
		return checkNagiosArtifact(a)
	case "smokeping":
		return checkSmokeArtifact(a)
	case "switch-core":
		return checkSwitchCoreArtifact(a)
	default:
		return errors.New("unknown provisioning artifact kind")
	}
}
func checkDNSArtifact(a Artifact) error {
	if !a.Complete || !strings.HasPrefix(a.Content, "; Generated by MoeDove IXP Manager. Complete reverse zone; not activated.\n") {
		return errors.New("expected complete generated reverse zone")
	}
	zone, err := SafeFQDN(a.Zone)
	if err != nil || zone != a.Zone || !reverseNameShape(zone, false) {
		return errors.New("invalid reverse zone origin")
	}
	soa, ns, origin, ttl := 0, 0, 0, 0
	inSOA := false
	numbers := []string{}
	for index, line := range strings.Split(a.Content, "\n") {
		if index == 0 {
			continue
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "$ORIGIN ") {
			if line != "$ORIGIN "+zone {
				return errors.New("zone origin mismatch")
			}
			origin++
			continue
		}
		if strings.HasPrefix(line, "$TTL ") {
			n, err := strconv.ParseUint(strings.TrimPrefix(line, "$TTL "), 10, 32)
			if err != nil || n == 0 || n > 604800 {
				return errors.New("invalid zone TTL")
			}
			ttl++
			continue
		}
		if match := soaStart.FindStringSubmatch(line); match != nil {
			if inSOA {
				return errors.New("nested SOA")
			}
			if _, err := SafeFQDN(match[1]); err != nil {
				return err
			}
			if _, err := SafeFQDN(match[2]); err != nil {
				return err
			}
			soa++
			inSOA = true
			continue
		}
		if inSOA {
			if line == ")" {
				inSOA = false
				continue
			}
			match := soaNumber.FindStringSubmatch(line)
			if match == nil {
				return errors.New("invalid SOA field")
			}
			if _, err := strconv.ParseUint(match[1], 10, 32); err != nil {
				return err
			}
			numbers = append(numbers, match[2])
			continue
		}
		if strings.HasPrefix(line, "@ IN NS ") {
			if _, err := SafeFQDN(strings.TrimPrefix(line, "@ IN NS ")); err != nil {
				return err
			}
			ns++
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 4 || fields[1] != "IN" || fields[2] != "PTR" {
			return errors.New("unsupported directive in reverse zone")
		}
		owner, err := SafeFQDN(fields[0])
		if err != nil || !reverseNameShape(owner, true) || (owner != zone && !strings.HasSuffix(owner, "."+zone)) {
			return errors.New("PTR owner outside requested zone")
		}
		if _, err = SafeFQDN(fields[3]); err != nil {
			return err
		}
	}
	if inSOA || soa != 1 || origin != 1 || ttl != 1 || ns < 1 || ns > 8 || strings.Join(numbers, ",") != "serial,refresh,retry,expire,minimum" {
		return errors.New("complete zone requires one SOA/origin/TTL and authoritative NS records")
	}
	return nil
}

// A PTR owner represents one complete address, not an arbitrary DNS label.
// Checking the label boundary also prevents BIND's out-of-zone ignore behavior
// from making a misplaced record look successfully validated.
func reverseNameShape(name string, full bool) bool {
	if strings.HasSuffix(name, ".in-addr.arpa.") {
		labels := strings.Split(strings.TrimSuffix(name, ".in-addr.arpa."), ".")
		if len(labels) < 1 || len(labels) > 4 || (full && len(labels) != 4) {
			return false
		}
		for _, label := range labels {
			n, err := strconv.ParseUint(label, 10, 8)
			if err != nil || strconv.FormatUint(n, 10) != label {
				return false
			}
		}
		return true
	}
	if strings.HasSuffix(name, ".ip6.arpa.") {
		labels := strings.Split(strings.TrimSuffix(name, ".ip6.arpa."), ".")
		if len(labels) < 1 || len(labels) > 32 || (full && len(labels) != 32) {
			return false
		}
		for _, label := range labels {
			if len(label) != 1 || !strings.Contains("0123456789abcdef", label) {
				return false
			}
		}
		return true
	}
	return false
}
func checkNagiosArtifact(a Artifact) error {
	if a.Complete || !strings.HasPrefix(a.Content, "# Generated by MoeDove IXP Manager. Include objects only;") {
		return errors.New("expected generated Nagios include")
	}
	block := ""
	hosts := map[string]bool{}
	references := []string{}
	have := map[string]bool{}
	for _, raw := range strings.Split(a.Content, "\n") {
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, "define ") && strings.HasSuffix(line, " {") {
			if block != "" {
				return errors.New("nested Nagios object")
			}
			block = strings.TrimSuffix(strings.TrimPrefix(line, "define "), " {")
			if block != "host" && block != "service" && block != "hostgroup" {
				return errors.New("unsupported Nagios object")
			}
			have = map[string]bool{}
			continue
		}
		if line == "}" {
			if block == "" {
				return errors.New("unexpected object end")
			}
			required := []string{"host_name", "use"}
			if block == "host" {
				required = append(required, "address", "alias")
			}
			if block == "service" {
				required = append(required, "service_description", "check_command")
			}
			if block == "hostgroup" {
				required = []string{"hostgroup_name", "alias", "members"}
			}
			for _, field := range required {
				if !have[field] {
					return fmt.Errorf("Nagios %s missing %s", block, field)
				}
			}
			block = ""
			continue
		}
		if block == "" {
			return errors.New("directive outside Nagios object")
		}
		pair := strings.SplitN(line, " ", 2)
		if len(pair) != 2 || have[pair[0]] {
			return errors.New("invalid or duplicate Nagios directive")
		}
		key, value := pair[0], strings.TrimSpace(pair[1])
		allowed := map[string]map[string]bool{
			"host":      {"use": true, "host_name": true, "alias": true, "address": true, "check_command": true, "active_checks_enabled": true},
			"service":   {"use": true, "host_name": true, "service_description": true, "check_command": true},
			"hostgroup": {"hostgroup_name": true, "alias": true, "members": true},
		}
		if !allowed[block][key] {
			return errors.New("directive not permitted in this Nagios object type")
		}
		have[key] = true
		switch key {
		case "use":
			for _, template := range strings.Split(value, ",") {
				if !safeIdentifier.MatchString(template) {
					return errors.New("invalid template reference")
				}
			}
		case "host_name":
			if !nagiosHostName.MatchString(value) {
				return errors.New("invalid generated host ID")
			}
			if block == "host" {
				if hosts[value] {
					return errors.New("duplicate host definition")
				}
				hosts[value] = true
			} else {
				references = append(references, value)
			}
		case "hostgroup_name":
			if !regexp.MustCompile(`^md_group_[a-f0-9]{20}$`).MatchString(value) {
				return errors.New("invalid hostgroup ID")
			}
		case "members":
			for _, host := range strings.Split(value, ",") {
				if !nagiosHostName.MatchString(host) {
					return errors.New("invalid hostgroup member")
				}
				references = append(references, host)
			}
		case "address":
			if _, err := targetAddress(Target{Address: value}); err != nil {
				return err
			}
		case "alias", "service_description":
			display, err := safeDisplay(value)
			if err != nil || display != value {
				return errors.New("unsafe display value")
			}
		case "active_checks_enabled":
			if block != "host" || value != "0" {
				return errors.New("unsupported active check override")
			}
		case "check_command":
			if value != "null" && !nagiosCheck.MatchString(value) {
				return errors.New("unsupported Nagios check command")
			}
		default:
			return errors.New("unsupported Nagios directive")
		}
	}
	if block != "" {
		return errors.New("unfinished Nagios object")
	}
	for _, reference := range references {
		if !hosts[reference] {
			return errors.New("Nagios service/group references a missing generated host")
		}
	}
	return nil
}
func checkSmokeArtifact(a Artifact) error {
	if a.Complete || !strings.HasPrefix(a.Content, "# Generated by MoeDove IXP Manager. Targets subtree only;") {
		return errors.New("expected generated Smokeping subtree")
	}
	sections := map[string]bool{}
	current := ""
	depth := 0
	baseDepth := 0
	fields := map[string]bool{}
	finish := func() error {
		if current == "" {
			return nil
		}
		if depth > baseDepth && (!fields["host"] || !fields["probe"] || !fields["menu"] || !fields["title"]) {
			return errors.New("incomplete Smokeping target")
		}
		return nil
	}
	for _, raw := range strings.Split(a.Content, "\n") {
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, "+") {
			if err := finish(); err != nil {
				return err
			}
			parts := strings.Fields(line)
			if len(parts) != 2 || strings.Trim(parts[0], "+") != "" || !safeIdentifier.MatchString(parts[1]) || sections[parts[1]] {
				return errors.New("invalid Smokeping heading")
			}
			sections[parts[1]] = true
			depth = len(parts[0])
			if baseDepth == 0 {
				baseDepth = depth
			}
			if baseDepth < 1 || baseDepth > 4 || depth < baseDepth || depth > baseDepth+1 {
				return errors.New("invalid Smokeping subtree depth")
			}
			current = parts[1]
			fields = map[string]bool{}
			continue
		}
		if current == "" {
			return errors.New("Smokeping assignment without section")
		}
		pair := strings.SplitN(line, "=", 2)
		if len(pair) != 2 {
			return errors.New("unsupported Smokeping directive")
		}
		key, value := strings.TrimSpace(pair[0]), strings.TrimSpace(pair[1])
		if fields[key] {
			return errors.New("duplicate Smokeping variable")
		}
		fields[key] = true
		switch key {
		case "menu", "title":
			display, err := safeDisplay(value)
			if err != nil || display != value {
				return errors.New("unsafe Smokeping label")
			}
		case "probe":
			if !safeIdentifier.MatchString(value) {
				return errors.New("invalid probe identifier")
			}
		case "host":
			if _, err := targetAddress(Target{Address: value}); err != nil {
				return err
			}
		default:
			return errors.New("unsupported Smokeping variable")
		}
	}
	return finish()
}

type cappedOutput struct {
	bytes.Buffer
	overflow bool
}

func (b *cappedOutput) Write(p []byte) (int, error) {
	n := len(p)
	if b.Len()+n > 65536 {
		b.overflow = true
		limit := 65536 - b.Len()
		if limit > 0 {
			b.Buffer.Write(p[:limit])
		}
		return n, nil
	}
	return b.Buffer.Write(p)
}
func command(ctx context.Context, binary string, args ...string) (string, error) {
	cmd := exec.CommandContext(ctx, binary, args...)
	var out cappedOutput
	cmd.Stdout = &out
	cmd.Stderr = &out
	err := cmd.Run()
	if ctx.Err() != nil {
		return "", ctx.Err()
	}
	if err != nil {
		return "", err
	}
	if out.overflow {
		return "", errors.New("validator output exceeded limit")
	}
	return out.String(), nil
}
