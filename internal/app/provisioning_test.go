func createMonitorProfile(c *client, name, kind string) Record {
	return c.ok("POST", "/api/resources/provisioning-profiles", Record{"name": name, "options": Record{"kind": kind, "families": []int{4, 6}}})
}

func approveProvision(c *client, revision Record) string {
	path := "/api/provisioning/" + str(revision, "id")
	c.ok("POST", path+"/validate", nil)
	c.ok("POST", path+"/approve", Record{"checksum": revision["checksum"]})
	return path
}

func TestProvisionProfilesCASReviewAndInventoryStaleness(t *testing.T) {
	c, dir, _ := credentialFixture(t)
	profile := createMonitorProfile(c, "Monitoring", "nagios")
	path := "/api/resources/provisioning-profiles/" + str(profile, "id")
	if w := c.request("PUT", path, Record{"name": "Changed", "options": profile["options"], "expectedRevision": "stale"}); w.Code != 409 {
		t.Fatal("stale profile edit accepted")
	}
	updated := c.ok("PUT", path, Record{"name": "Changed", "options": profile["options"], "expectedRevision": profile["revision"]})
	if updated["revision"] == profile["revision"] {
		t.Fatal("profile edit did not advance revision")
	}
	revision := c.ok("POST", "/api/provisioning", Record{"profileId": profile["id"]})
	if revision["config"] != nil || revision["complete"] != false || revision["validationLevel"] != "structural" {
		t.Fatal("include fragment mislabeled as a complete native-validated configuration")
	}
	list := c.ok("GET", "/api/provisioning", nil)["items"].([]any)
	if list[0].(map[string]any)["config"] != nil {
		t.Fatal("list contains artifact bodies")
	}
	detail := c.ok("GET", "/api/provisioning/"+str(revision, "id"), nil)
	if detail["redacted"] != true || !strings.Contains(str(detail, "config"), "define host") {
		t.Fatal("missing safe typed preview")
	}
	route := approveProvision(c, revision)
	w := c.request("GET", route+"/config", nil)
	if w.Code != 200 || w.Header().Get("X-Provisioning-Profile-ID") != str(profile, "id") || w.Header().Get("X-Provisioning-Kind") != "nagios" || w.Header().Get("X-Config-SHA256") != digest(w.Body.String()) || w.Header().Get("X-Config-SHA256") == str(revision, "checksum") {
		t.Fatal("download target or real checksum is not bound correctly")
	}
	stateBytes, err := os.ReadFile(filepath.Join(dir, "state.json"))
	if err != nil || bytes.Contains(stateBytes, []byte("Generated by MoeDove IXP Manager. Include objects")) {
		t.Fatal("configuration body remained in hot state")
	}
	connections := c.ok("GET", "/api/resources/connections", nil)["items"].([]any)
	connection := Record(connections[0].(map[string]any))
	edit := editableCredentialPeer(connection)
	// API member-safe projections may carry computed port details; use the
	// canonical stored fixture for a legitimate full-replacement resource edit.
	snapshot := c.a.store.Snapshot()
	edit = editableCredentialPeer(find(&snapshot, "connections", str(connection, "id")))
	delete(edit, "ownershipSince")
	delete(edit, "bindingSince")
	edit["canPing4"] = false
	c.ok("PUT", "/api/resources/connections/"+str(connection, "id"), edit)
	if w := c.request("GET", route+"/config", nil); w.Code != 409 {
		t.Fatal("inventory change did not invalidate approved monitoring output")
	}
	newer := c.ok("POST", "/api/provisioning", Record{"profileId": profile["id"]})
	newPath := approveProvision(c, newer)
	if w := c.request("POST", newPath+"/prune", Record{"checksum": newer["checksum"], "acknowledge": true}); w.Code != 409 {
		t.Fatal("current approved configuration pruned")
	}
	edit["canPing4"] = true
	c.ok("PUT", "/api/resources/connections/"+str(connection, "id"), edit)
	if w := c.request("GET", route+"/config", nil); w.Code != 200 {
		t.Fatal("restored intent did not match the original reviewed configuration")
	}
	if w := c.request("POST", route+"/prune", Record{"checksum": revision["checksum"], "acknowledge": true}); w.Code != 409 {
		t.Fatal("only approved configuration matching current intent was pruned")
	}
	matching := c.ok("POST", "/api/provisioning", Record{"profileId": profile["id"]})
	approveProvision(c, matching)
	c.ok("POST", route+"/prune", Record{"checksum": revision["checksum"], "acknowledge": true})
	diff := c.ok("GET", newPath+"/diff", nil)
	if diff["baseUnavailable"] != true || diff["redacted"] != true {
		t.Fatal("pruned baseline presented as a complete diff")
	}
	c.ok("DELETE", route, Record{"checksum": revision["checksum"], "acknowledge": true, "reason": "retention completed"})
}

func TestProvisioningScopesBindProfilesAndForbidApproval(t *testing.T) {
	c, _, _ := credentialFixture(t)
	one := createMonitorProfile(c, "One", "smokeping")
	two := createMonitorProfile(c, "Two", "nagios")
	first := c.ok("POST", "/api/provisioning", Record{"profileId": one["id"]})
	second := c.ok("POST", "/api/provisioning", Record{"profileId": two["id"]})
	firstPath := approveProvision(c, first)
	secondPath := approveProvision(c, second)
	request := Record{"name": "Provision agent", "currentPassword": "very-long-test-password", "scopes": []string{"provisioning:read", "provisioning:write", "provisioning:pull"}}
	if w := c.request("POST", "/api/account/tokens", request); w.Code != 403 {
		t.Fatal("unbound provisioning token issued")
	}
	request["profileIds"] = []string{str(one, "id")}
	raw := str(c.ok("POST", "/api/account/tokens", request), "token")
	for _, route := range []string{firstPath + "/config", "/api/provisioning", "/api/resources/provisioning-profiles"} {
		if w := bearerRequest(c.a, raw, "GET", route, nil); w.Code != 200 {
			t.Fatal("bound token read failed", route, w.Code)
		}
	}
	if w := bearerRequest(c.a, raw, "GET", secondPath+"/config", nil); w.Code != 403 {
		t.Fatal("pull token read another profile")
	}
	if w := bearerRequest(c.a, raw, "POST", "/api/provisioning", Record{"profileId": two["id"]}); w.Code != 403 {
		t.Fatal("write token generated another profile")
	}
	if w := bearerRequest(c.a, raw, "POST", firstPath+"/approve", Record{"checksum": first["checksum"]}); w.Code != 403 {
		t.Fatal("token approved a configuration")
	}
	if w := bearerRequest(c.a, raw, "PUT", "/api/resources/provisioning-profiles/"+str(one, "id"), Record{"name": "Injected", "options": one["options"], "expectedRevision": one["revision"]}); w.Code != 403 {
		t.Fatal("token edited a profile")
	}
	c.create("users", Record{"name": "Viewer", "email": "provision-viewer@example.net", "role": "viewer", "password": "viewer-long-password"})
	viewer := docLoginClient(t, c.a, "provision-viewer@example.net", "viewer-long-password")
	viewer.ok("GET", firstPath, nil)
	if w := viewer.request("GET", firstPath+"/config", nil); w.Code != 403 {
		t.Fatal("viewer downloaded private configuration")
	}
}

func TestDNSProfilesRequireSerialEvidenceAndExactPrefix(t *testing.T) {
	c, _, peer := credentialFixture(t)
	router := c.ok("GET", "/api/resources/routers/"+str(peer, "routerId"), nil)
	options := Record{"kind": "dns-arpa", "vlanId": router["vlanId"], "families": []int{4}, "dns": Record{"prefix": "192.0.2.0/24", "primaryNS": "ns1.example.net.", "responsibleMailbox": "hostmaster.example.net.", "nameServers": []string{"ns1.example.net."}, "nameSuffix": "ix.example.net."}}
	request := Record{"name": "Existing DNS", "options": options}
	if w := c.request("POST", "/api/resources/provisioning-profiles", request); w.Code != 400 {
		t.Fatal("existing DNS serial was silently guessed")
	}
	request["dnsSerialFloor"] = uint32(2026110701)
	profile := c.ok("POST", "/api/resources/provisioning-profiles", request)
	if w := c.request("POST", "/api/resources/provisioning-profiles", request); w.Code != 400 {
		t.Fatal("two profiles could replace the same authoritative zone")
	}
	revision := c.ok("POST", "/api/provisioning", Record{"profileId": profile["id"]})
	s := c.a.store.Snapshot()
	stored := s.ProvisionRevisions[0]
	if stored.Options.DNS.Serial != 2026110702 {
		t.Fatal("new DNS serial did not advance the explicit existing baseline")
	}
	if revision["validationLevel"] != "native" || revision["complete"] != true {
		t.Fatal("DNS validation capability incorrect")
	}
	c.a.namedCheckzone = "/not-installed/named-checkzone"
	path := "/api/provisioning/" + str(revision, "id")
	if w := c.request("POST", path+"/validate", nil); w.Code != 422 {
		t.Fatal("missing native DNS checker accepted")
	}
	if w := c.request("POST", path+"/approve", Record{"checksum": revision["checksum"]}); w.Code != 409 {
		t.Fatal("unvalidated DNS approved")
	}
	export := c.ok("GET", "/api/export", nil)["resources"].(map[string]any)[provisionProfileKind].([]any)[0].(map[string]any)
	if export["dnsNewZone"] != false || export["dnsSerialFloor"] != float64(2026110702) {
		t.Fatal("resource export could reset issued DNS serials")
	}
	if w := c.request("DELETE", "/api/resources/vlans/"+str(router, "vlanId"), nil); w.Code != 400 {
		t.Fatal("DNS profile VLAN removed")
	}
	if binary := os.Getenv("NAMED_CHECKZONE_BIN"); binary != "" {
		c.a.namedCheckzone = binary
		newer := c.ok("POST", "/api/provisioning", Record{"profileId": profile["id"]})
		c.ok("POST", path+"/validate", nil)
		newPath := approveProvision(c, newer)
		if w := c.request("POST", path+"/approve", Record{"checksum": revision["checksum"]}); w.Code != 409 {
			t.Fatal("older candidate approved after newer DNS serial")
		}
		latest := c.ok("POST", "/api/provisioning", Record{"profileId": profile["id"]})
		approveProvision(c, latest)
		if w := c.request("GET", newPath+"/config", nil); w.Code != 409 {
			t.Fatal("superseded DNS serial remained downloadable")
		}
	}
}

func TestEncryptedArtifactNamespacesCannotBeConfused(t *testing.T) {
	c, _ := setupClient(t)
	const id = "same-revision-id"
	const content = "namespace fixture"
	var file encryptedArtifactFile
	if err := c.a.store.Update(func(s *State) error {
		var err error
		file, err = c.a.writeEncryptedArtifactLocked("deployments", id, digest(content), content)
		return err
	}); err != nil {
		t.Fatal(err)
	}
	raw, err := os.ReadFile(filepath.Join(c.a.deploymentDir(), id+".enc"))
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(c.a.encryptedArtifactDir("provisioning"), id+".enc"), raw, 0600); err != nil {
		t.Fatal(err)
	}
	c.a.store.mu.RLock()
	_, err = c.a.readEncryptedArtifactLocked("provisioning", id, digest(content), file)
	c.a.store.mu.RUnlock()
	if err == nil {
		t.Fatal("copied router ciphertext decrypted as a provisioning artifact")
	}
}

func TestDNSSerialFloorSurvivesProfileRecreation(t *testing.T) {
	state := State{ProvisionSerials: map[string]uint32{"2.0.192.in-addr.arpa.": 2026110799}}
	options := provision.Options{Kind: "dns-arpa", DNS: provision.DNSOptions{Prefix: "192.0.2.0/24"}}
	profile := Record{"dnsNewZone": true}
	next, err := allocateProvisionSerial(&state, profile, options)
	if err != nil || next != 2026110800 {
		t.Fatal("recreating profile reset SOA serial", err)
	}
	state.ProvisionSerials["2.0.192.in-addr.arpa."] = ^uint32(0)
	if next, err := allocateProvisionSerial(&state, profile, options); err != nil || next != 1 {
		t.Fatal("known zone did not advance across the RFC1982 wrap", err)
	}
	// Persisted serials use exact uint32 values, not timestamp strings.
	b, err := json.Marshal(state)
	if err != nil || !bytes.Contains(b, []byte(`"2.0.192.in-addr.arpa.":1`)) {
		t.Fatal("serial precision lost")
	}
}
